function definition = nhpulseStageSettings(stageKey)
% NHPULSESTAGESETTINGS Return the UI/configuration schema for one stage.
%
% definition = nhpulseStageSettings(stageKey) returns an explicit schema
% used by nhpulseResolveStageSettings and nhpulseEditStageSettings. The
% schema describes service-level settings rather than every low-level
% engine option. Advanced engine options remain available as a structure.

    stageKey = lower(char(stageKey));
    common = [ ...
        fieldDef('force', 'Recompute output', 'logical', true, '', {}, ...
            'Replace a reusable output instead of accepting the current file.'), ...
        fieldDef('showFigures', 'Show figures', 'logical', true, '', {}, ...
            'Open the interactive or quality-control figure for this stage.'), ...
        fieldDef('saveFigures', 'Save QC figures', 'logical', true, '', {}, ...
            'Save quality-control figures with the stage output.')];

    switch stageKey
        case 'crop'
            fields = [ ...
                fieldDef('cropPlaneMode', 'Crop-plane behavior', 'choice', ...
                    'select', '', {'select', 'autoSelect', 'reuse'}, ...
                    ['select always opens the crop tool; autoSelect reuses a ', ...
                    'compatible plane when available; reuse requires one.']), ...
                fieldDef('skinMaxFaces', 'Printable scalp faces', 'number', ...
                    1200, 'faces', {}, ...
                    'Target face count for the cropped manufacturing scalp.'), ...
                common];
            presets = [ ...
                preset('guided', 'Guided', ...
                    'Open the crop tool and build a practical manufacturing mesh.', ...
                    struct('cropPlaneMode', 'select', 'skinMaxFaces', 1200, ...
                    'force', true)), ...
                preset('reuse', 'Reuse accepted crop', ...
                    'Reuse an existing compatible crop plane without reopening it.', ...
                    struct('cropPlaneMode', 'reuse', 'skinMaxFaces', 1200, ...
                    'force', false)), ...
                preset('detailed', 'Higher-detail mesh', ...
                    'Keep more scalp faces for inspection or detailed fabrication.', ...
                    struct('cropPlaneMode', 'select', 'skinMaxFaces', 3000, ...
                    'force', true))];
            definition = stageDef(stageKey, 'Printable crop settings', ...
                ['Control how the printer-bed crop is selected and how much ', ...
                'surface detail is retained.'], fields, presets, 'engineOptions');

        case 'exclusions'
            fields = [editModeField(), common];
            presets = standardEditPresets();
            definition = stageDef(stageKey, 'Exclusion settings', ...
                'Control whether saved ear and painted exclusions are reused or edited.', ...
                fields, presets, 'engineOptions');

        case 'fiducials'
            fields = [editModeField(), ...
                fieldDef('meshStage', 'Selection surface', 'choice', 'fullHead', ...
                    '', {'fullHead', 'cropped'}, ...
                    'Choose the scalp representation used for landmark picking.'), ...
                common];
            presets = standardEditPresets();
            definition = stageDef(stageKey, 'Fiducial settings', ...
                'Control landmark selection and reuse behavior.', fields, presets, ...
                'engineOptions');

        case 'target'
            fields = [ ...
                fieldDef('orientationCode', 'Anatomical orientation', 'choice', ...
                    'ras', '', {'ras', 'las', 'lps', 'radiological'}, ...
                    'Orientation used by the target voxel picker.'), ...
                fieldDef('closeFigure', 'Close picker after acceptance', ...
                    'logical', false, '', {}, ...
                    'Close the target-selection figure after accepting the voxel.'), ...
                common(2:3)];
            presets = preset('guided', 'Guided', ...
                'Interactively choose one target voxel.', struct());
            definition = stageDef(stageKey, 'Target settings', ...
                'Control the interactive target-selection view.', fields, presets, ...
                'engineOptions');

        case 'implant'
            fields = [ ...
                fieldDef('interactive', 'Refine placement interactively', ...
                    'logical', true, '', {}, ...
                    'Open the implant placement GUI after initialization.'), ...
                fieldDef('marginMm', 'Keepout margin', 'number', 5, 'mm', {}, ...
                    'Additional cap clearance around the accepted implant placement.'), ...
                common];
            presets = [ ...
                preset('guided', 'Guided', 'Refine placement and use a 5 mm keepout.', ...
                    struct('interactive', true, 'marginMm', 5)), ...
                preset('tight', 'Tight keepout', ...
                    'Refine placement and use a smaller 3 mm keepout.', ...
                    struct('interactive', true, 'marginMm', 3))];
            definition = stageDef(stageKey, 'Implant settings', ...
                'Control implant refinement and cap clearance.', fields, presets, ...
                'placementOptions');

        case 'retention'
            fields = [editModeField(), common];
            presets = standardEditPresets();
            definition = stageDef(stageKey, 'Velcro retention settings', ...
                'Control automatic placement, manual refinement, and replay of anchors.', ...
                fields, presets, 'plannerOptions');

        otherwise
            error('nhpulseStageSettings:UnknownStage', ...
                'No settings schema is registered for stage "%s".', stageKey);
    end
end

function value = stageDef(key, titleText, description, fields, presets, advancedField)
    value = struct('schema', 'nhpulse.stageSettings', 'schemaVersion', 1, ...
        'stageKey', key, 'title', titleText, 'description', description, ...
        'defaultPreset', presets(1).key, 'fields', fields, ...
        'presets', presets, 'advancedOptionField', advancedField);
end

function value = fieldDef(name, label, type, defaultValue, units, choices, helpText)
    value = struct('name', name, 'label', label, 'type', type, ...
        'defaultValue', defaultValue, 'units', units, 'choices', {choices}, ...
        'help', helpText, 'minimum', [], 'maximum', []);
end

function value = editModeField()
    value = fieldDef('editMode', 'Saved-result behavior', 'choice', 'always', ...
        '', {'always', 'auto', 'never'}, ...
        ['always opens the editor; auto reuses a compatible saved result; ', ...
        'never requires a reusable saved result.']);
end

function values = standardEditPresets()
    values = [ ...
        preset('guided', 'Guided', 'Open the editor so the result can be checked.', ...
            struct('editMode', 'always', 'force', true)), ...
        preset('reuse', 'Reuse when compatible', ...
            'Reuse a compatible accepted result, otherwise open the editor.', ...
            struct('editMode', 'auto', 'force', false)), ...
        preset('replay', 'Replay only', ...
            'Require and reuse an existing compatible result.', ...
            struct('editMode', 'never', 'force', false))];
end

function value = preset(key, label, description, values)
    value = struct('key', key, 'label', label, ...
        'description', description, 'values', values);
end
