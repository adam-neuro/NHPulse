function report = nhpulseTestPrinterCoupons()
% NHPULSETESTPRINTERCOUPONS Exercise the public printer-test generators.

    root = tempname;
    cleaner = onCleanup(@() cleanupFolder(root));
    mkdir(root);

    flat = nhpulseMakeDualMaterialPrintCoupon( ...
        'outputDir', fullfile(root, 'flat'), ...
        'force', true, 'showFigures', false, 'saveFigures', false, ...
        'verbose', false);
    dome = nhpulseMakeDomeRailPrintCoupon( ...
        'outputDir', fullfile(root, 'dome'), ...
        'radialDivisions', 3, 'angularDivisions', 8, ...
        'voxelSizeMm', 0.75, ...
        'force', true, 'showFigures', false, 'saveFigures', false, ...
        'verbose', false);
    localCrop = nhpulseCropDualMaterialPrint(dome.reportMat, ...
        'centerMm', [0 0 4], 'sizeMm', [18 18 10], ...
        'voxelSizeMm', 0.75, ...
        'outputDir', fullfile(root, 'crop'), ...
        'force', true, 'showFigures', false, 'saveFigures', false, ...
        'verbose', false);

    products = {flat.plaStlFile, flat.tpeStlFile, flat.reportMat, ...
        dome.plaStlFile, dome.tpeStlFile, dome.reportMat, ...
        localCrop.plaStlFile, localCrop.tpeStlFile, localCrop.reportMat};
    for i = 1:numel(products)
        info = dir(products{i});
        assert(~isempty(info) && info.bytes > 0, ...
            'Missing or empty printer-test product: %s', products{i});
    end

    assert(flat.meshes.pla.faces > 0 && flat.meshes.tpe.faces > 0);
    assert(dome.meshes.pla.faces > 0 && dome.meshes.tpe.faces > 0);
    assert(localCrop.meshes.pla.faces > 0 && localCrop.meshes.tpe.faces > 0);

    report = struct('passed', true, 'productCount', numel(products), ...
        'flat', flat.meshes, 'dome', dome.meshes, ...
        'localCrop', localCrop.meshes);
    fprintf('NHPulse printer-coupon tests passed (%d products).\n', ...
        numel(products));
end

function cleanupFolder(folder)
    if exist(folder, 'dir') == 7
        rmdir(folder, 's');
    end
end
