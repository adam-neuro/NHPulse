function value = medianFinite(x)
    x = x(isfinite(x));
    if isempty(x)
        value = NaN;
    else
        value = median(x);
    end
end

function value = meanFinite(x)
    x = x(isfinite(x));
    if isempty(x)
        value = NaN;
    else
        value = mean(x);
    end
end

function value = percentileLocal(x, pct)
    x = sort(x(isfinite(x)));
    if isempty(x)
        value = NaN;
        return;
    end
    pos = 1 + (numel(x) - 1) * pct / 100;
    lo = floor(pos);
    hi = ceil(pos);
    if lo == hi
        value = x(lo);
    else
        value = x(lo) + (pos - lo) * (x(hi) - x(lo));
    end
end

function value = max0(x)
    if isempty(x)
        value = 0;
    else
        value = max(x);
    end
end

function printSummary(out)
    fprintf('\nScalp trace warp\n');
    fprintf('  trace: %s (%d points)\n', out.trace.name, ...
        size(out.trace.coordinatesMm, 1));
    fprintf('  warped cache: %s\n', out.outputFile);
    if isfield(out.mesh, 'fitCoordinateFrame')
        fprintf('  warp fit frame: %s\n', out.mesh.fitCoordinateFrame);
    end
    fprintf('  usable trace points: %d\n', out.warp.summary.nUsableTracePoints);
    fprintf('  median trace distance: %.3g mm\n', ...
        out.warp.summary.medianTraceDistanceMm);
    fprintf('  median displacement: %.3g mm\n', ...
        out.warp.summary.medianDisplacementMm);
    fprintf('  max displacement: %.3g mm\n', ...
        out.warp.summary.maxDisplacementMm);
    if isfield(out.warp, 'dentRepair') && ...
            isstruct(out.warp.dentRepair) && ...
            ~strcmpi(out.warp.dentRepair.mode, 'off')
        dr = out.warp.dentRepair;
        fprintf(['  post-warp dent repair: %s, initial/final flags ', ...
            '%d/%d, repaired %d vertices, metric %s, max move %.3g mm, ', ...
            'max dent %.3g -> %.3g mm\n'], ...
            dr.mode, ...
            safeScalarField(dr, 'nVerticesFlaggedInitial', 0), ...
            safeScalarField(dr, 'nVerticesFlaggedFinal', 0), ...
            safeScalarField(dr, 'nVerticesRepaired', 0), ...
            char(getOptionalField(dr, 'metric', 'unknown')), ...
            safeScalarField(dr, 'maxRepairMoveMm', 0), ...
            safeScalarField(dr, 'maxDentDepthBeforeMm', NaN), ...
            safeScalarField(dr, 'maxDentDepthAfterMm', NaN));
    end
    if isfield(out.warp, 'surfaceSmoothing') && ...
            isstruct(out.warp.surfaceSmoothing) && ...
            ~strcmpi(out.warp.surfaceSmoothing.mode, 'none')
        ss = out.warp.surfaceSmoothing;
        fprintf(['  post-warp surface smoothing: %s, %d iterations, ', ...
            'median move %.3g mm, roughness %.3g -> %.3g mm\n'], ...
            ss.mode, ss.iterations, ss.medianMoveMm, ...
            ss.medianRoughnessBeforeMm, ss.medianRoughnessAfterMm);
    end
    if isfield(out.warp, 'normalOrientation') && ...
            isstruct(out.warp.normalOrientation)
        ni = out.warp.normalOrientation;
        fprintf('  normal orientation: %s requested, %s applied, %.1f%% flipped\n', ...
            ni.requestedMode, ni.appliedMode, ...
            100 * safeScalarField(ni, 'flipFraction', 0));
    end
    if isfield(out.warp, 'directionInfo') && ...
            isstruct(out.warp.directionInfo)
        di = out.warp.directionInfo;
        fprintf('  warp direction: %s, mean radial weight %.3g\n', ...
            di.mode, safeScalarField(di, 'meanRadialWeight', 0));
    end
    if isfield(out.roast, 'maskFile') && ~isempty(out.roast.maskFile)
        fprintf('  ROAST warped mask: %s\n', out.roast.maskFile);
        if isfield(out.roast, 'coordinateMapping') && ...
                ~isempty(out.roast.coordinateMapping)
            fprintf('  ROAST mask coordinate mapping: %s\n', ...
                out.roast.coordinateMapping);
        end
        if isfield(out.roast, 'skinVoxelization') && ...
                isstruct(out.roast.skinVoxelization)
            sv = out.roast.skinVoxelization;
            fprintf('  ROAST skin voxel mode: %s, marked %d voxels\n', ...
                sv.mode, safeScalarField(sv, 'nVoxelsMarkedSkin', 0));
            if isfield(sv, 'surfaceVoxelDiagnostics') && ...
                    isstruct(sv.surfaceVoxelDiagnostics)
                vd = sv.surfaceVoxelDiagnostics;
                dmm = getOptionalField(vd, 'centerShiftMmApprox', [nan nan nan]);
                fprintf(['  ROAST warped surface center shift: ', ...
                    '[%.2f %.2f %.2f] mm approx\n'], ...
                    dmm(1), dmm(2), dmm(3));
            end
            if isfield(sv, 'fallbackMode') && ~isempty(sv.fallbackMode)
                fprintf('  ROAST skin voxel fallback: %s\n', sv.fallbackMode);
            end
        end
        if isfield(out.roast, 'preWarpSkinCleanup') && ...
                isstruct(out.roast.preWarpSkinCleanup)
            sc0 = out.roast.preWarpSkinCleanup;
            fprintf(['  ROAST pre-warp skin cleanup: %s, components %d -> %d, ', ...
                'removed %d voxels\n'], ...
                sc0.mode, sc0.componentCountBefore, ...
                sc0.keptComponentCount, sc0.removedSkinVoxels);
        end
        if isfield(out.roast, 'skinCleanup') && ...
                isstruct(out.roast.skinCleanup)
            sc = out.roast.skinCleanup;
            fprintf(['  ROAST skin cleanup: %s, components %d -> %d, ', ...
                'removed %d voxels\n'], ...
                sc.mode, sc.componentCountBefore, sc.keptComponentCount, ...
                sc.removedSkinVoxels);
        end
    end
    if ~isempty(out.qcFigure)
        fprintf('  QC figure: %s\n', out.qcFigure);
    end
end
