function [S, source] = loadSkinCacheStruct(value)
    source = struct('type', '', 'file', '', 'label', '', ...
        'cacheFile', '', 'coordinateFrame', 'capMakerPrintMm');
    if isa(value, 'triangulation')
        S = struct('TRskin', value, 'meta', struct());
        source.type = 'triangulation';
        source.label = 'triangulation';
        return;
    end
    if isstruct(value) && isfield(value, 'TRskin')
        S = value;
        source.type = 'skinStruct';
        source.label = 'skin struct';
        return;
    end
    if isstruct(value) && isfield(value, 'file') && ~isempty(value.file)
        value = value.file;
    elseif isstruct(value) && isfield(value, 'source') && ...
            isstruct(value.source) && isfield(value.source, 'file') && ...
            ~isempty(value.source.file)
        value = value.source.file;
    elseif isstruct(value) && isfield(value, 'layout') && ...
            isfield(value.layout, 'skin') && ...
            isfield(value.layout.skin, 'cacheFile')
        value = value.layout.skin.cacheFile;
    elseif isstruct(value) && isfield(value, 'skin') && ...
            isstruct(value.skin) && isfield(value.skin, 'cacheFile')
        value = value.skin.cacheFile;
    end
    if ~(ischar(value) || isstring(value))
        error('acsWarpScalpSurfaceToPolhemusTrace:BadSkinSource', ...
            'Could not resolve a skin cache from the supplied surface source.');
    end
    fileName = expandUserPath(char(value));
    if exist(fileName, 'file') ~= 2
        error('acsWarpScalpSurfaceToPolhemusTrace:SkinCacheNotFound', ...
            'Skin cache not found: %s', fileName);
    end
    raw = load(fileName);
    if isfield(raw, 'TRskin')
        S = raw;
    else
        S = firstStruct(raw);
    end
    source.type = 'skinCache';
    source.file = fileName;
    source.cacheFile = fileName;
    source.label = stripMatExtension(getFileName(fileName));
end

function TR = ensureTriangulation(value)
    if isa(value, 'triangulation')
        TR = value;
    elseif isstruct(value) && isfield(value, 'ConnectivityList') && ...
            isfield(value, 'Points')
        TR = triangulation(double(value.ConnectivityList), double(value.Points));
    else
        error('acsWarpScalpSurfaceToPolhemusTrace:BadTriangulation', ...
            'Expected a triangulation or struct with Points/ConnectivityList.');
    end
end

function trace = readTracePoints(value, opts)
    trace = struct('name', '', 'coordinatesMm', zeros(0, 3), ...
        'labels', {{}}, 'rows', [], 'source', struct());
    if isTraceOverlay(value) && isfield(value, 'traceSets') && ...
            ~isempty(value.traceSets)
        traceSets = value.traceSets;
        useRows = selectTraceSetRows(traceSets, opts.traceSetName);
        coords = zeros(0, 3);
        labels = {};
        rows = [];
        names = cell(numel(useRows), 1);
        for i = 1:numel(useRows)
            ts = traceSets(useRows(i));
            coords = [coords; double(ts.coordinatesMm)]; %#ok<AGROW>
            if isfield(ts, 'labels') && ~isempty(ts.labels)
                labels = [labels; normalizeLabelCell(ts.labels)]; %#ok<AGROW>
            else
                labels = [labels; defaultLabels(size(ts.coordinatesMm, 1), 'trace')]; %#ok<AGROW>
            end
            if isfield(ts, 'rows') && ~isempty(ts.rows)
                rows = [rows; double(ts.rows(:))]; %#ok<AGROW>
            else
                rows = [rows; nan(size(ts.coordinatesMm, 1), 1)]; %#ok<AGROW>
            end
            names{i} = char(ts.name);
        end
        trace.name = strjoin(names, '+');
        trace.coordinatesMm = coords;
        trace.labels = labels;
        trace.rows = rows;
        trace.coordinateFrame = traceOverlayCoordinateFrame(value);
        if isfield(value, 'excludedCoordinatesMm') && ...
                ~isempty(value.excludedCoordinatesMm)
            trace.excludedCoordinatesMm = double(value.excludedCoordinatesMm);
        end
        trace.source = getOptionalField(value, 'source', ...
            getOptionalField(value, 'meshSource', struct()));
        return;
    end
    if isstruct(value) && isfield(value, 'registration')
        trace = readTracePoints(value.registration, opts);
        return;
    end
    if isstruct(value) && isfield(value, 'registeredObjects') && ...
            ~isempty(value.registeredObjects)
        objects = value.registeredObjects;
        idx = selectObjectRows(objects, opts.traceSetName);
        coords = zeros(0, 3);
        labels = {};
        rows = [];
        names = cell(numel(idx), 1);
        for i = 1:numel(idx)
            obj = objects(idx(i));
            if isfield(obj, 'transformedCoordinatesMm') && ...
                    ~isempty(obj.transformedCoordinatesMm)
                P = double(obj.transformedCoordinatesMm);
            elseif isfield(obj, 'coordinatesMm') && ~isempty(obj.coordinatesMm)
                P = double(obj.coordinatesMm);
            else
                continue;
            end
            coords = [coords; P]; %#ok<AGROW>
            labels = [labels; objectLabels(obj, size(P, 1))]; %#ok<AGROW>
            if isfield(obj, 'rows') && ~isempty(obj.rows)
                rows = [rows; double(obj.rows(:))]; %#ok<AGROW>
            else
                rows = [rows; nan(size(P, 1), 1)]; %#ok<AGROW>
            end
            names{i} = objectName(obj, idx(i));
        end
        trace.name = strjoin(names, '+');
        trace.coordinatesMm = coords;
        trace.labels = labels;
        trace.rows = rows;
        return;
    end
    if isstruct(value) && isfield(value, 'transformedSourcePointsMm')
        points = double(value.transformedSourcePointsMm);
        labels = {};
        if isfield(value, 'sourceLabels')
            labels = normalizeLabelCell(value.sourceLabels);
        end
        if isempty(labels) || numel(labels) ~= size(points, 1)
            labels = defaultLabels(size(points, 1), 'point');
        end
        keep = true(size(points, 1), 1);
        if isfield(value, 'tracePointRows') && ~isempty(value.tracePointRows)
            keep = false(size(points, 1), 1);
            rows = double(value.tracePointRows(:));
            rows = rows(isfinite(rows) & rows >= 1 & rows <= size(points, 1));
            keep(rows) = true;
        end
        trace.name = 'trace';
        trace.coordinatesMm = points(keep, :);
        trace.labels = labels(keep);
        trace.rows = find(keep);
        trace.source = getOptionalField(value, 'meshSource', struct());
        return;
    end
    if ischar(value) || isstring(value)
        S = loadStructFile(char(value));
        trace = readTracePoints(S, opts);
        return;
    end
    if isnumeric(value) && size(value, 2) == 3
        trace.name = 'numericTrace';
        trace.coordinatesMm = double(value);
        trace.labels = defaultLabels(size(value, 1), 'trace');
        trace.rows = (1:size(value, 1))';
        return;
    end
end

