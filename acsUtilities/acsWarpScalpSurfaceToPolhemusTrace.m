            'Could not find object "%s". Available: %s', ...
            requestedName, strjoin(names, ', '));
    end
    idx = hit;
end

function warp = estimateSurfaceWarp(TR, tracePoints, opts)
    V = double(TR.Points);
    F = double(TR.ConnectivityList);
    N = vertexNormal(TR);
    N = normalizeRows(N);
    [N, normalInfo] = prepareWarpNormals(V, N, opts);
    [D, directionInfo] = prepareWarpDirections(V, N, opts);
    [nearestIdx, nearestDist] = nearestRows(V, tracePoints, 2500);
    traceDelta = tracePoints - V(nearestIdx, :);
    [radialUnit, ~] = radialDirections(V);
    signedOffsetWarp = sum(traceDelta .* D(nearestIdx, :), 2);
    signedOffsetNormal = sum(traceDelta .* N(nearestIdx, :), 2);
    signedOffsetRadial = sum(traceDelta .* radialUnit(nearestIdx, :), 2);
    signedOffset = chooseSignedOffset(signedOffsetWarp, signedOffsetNormal, ...
        signedOffsetRadial, opts);
    if normalInfo.allowGlobalTraceFlip && opts.inflateOnly && ...
            medianFinite(signedOffset) < 0 && ...
            medianFinite(abs(signedOffset)) > 1
        N = -N;
        D = -D;
        signedOffsetWarp = -signedOffsetWarp;
        signedOffsetNormal = -signedOffsetNormal;
        signedOffset = chooseSignedOffset(signedOffsetWarp, ...
            signedOffsetNormal, signedOffsetRadial, opts);
        normalInfo.globalTraceFlipped = true;
        normalInfo.appliedMode = 'globalTrace';
        normalInfo.nFlipped = size(N, 1);
        normalInfo.flipFraction = 1;
        directionInfo.globalTraceFlipped = true;
    end

    nearSurface = isfinite(signedOffset) & isfinite(nearestDist) & ...
        nearestDist <= opts.maxTraceDistanceMm;
    coverageValid = nearSurface;
    offset = opts.displacementScale .* signedOffset;
    if opts.inflateOnly
        offset = max(0, offset);
        valid = nearSurface & offset > 0;
        coverageValid = nearSurface & ...
            signedOffset >= -opts.coverageOffsetToleranceMm;
    else
        valid = nearSurface;
    end
    if ~any(coverageValid)
        coverageValid = valid;
    end
    if ~any(valid)
        warning('acsWarpScalpSurfaceToPolhemusTrace:NoPositiveTraceOffsets', ...
            ['No usable outward trace offsets were found. Returning an ', ...
             'unwarped surface. Check registration and normal orientation.']);
        displacement = zeros(size(V, 1), 1);
    else
        cap = min(opts.maxInflationMm, ...
            percentileLocal(offset(valid), opts.robustUpperPercentile));
        if ~isfinite(cap) || cap <= 0
            cap = opts.maxInflationMm;
        end
        offset = min(offset, cap);
        seedOffset = aggregateSeedOffsets(nearestIdx(valid), offset(valid), ...
            size(V, 1), opts);
        seeded = isfinite(seedOffset);
        seedOffset(~seeded) = 0;
        displacement = smoothVertexScalars(F, seedOffset, seeded, opts);
        traceDistToVertices = minDistanceToRows(V, tracePoints(coverageValid, :), 2500);
        attenuation = exp(-0.5 * (traceDistToVertices ./ opts.influenceSigmaMm) .^ 2);
        attenuation(traceDistToVertices > opts.influenceRadiusMm) = 0;
        displacement = displacement .* attenuation;
        if opts.inflateOnly
            displacement = max(0, displacement);
        end
        displacement = min(displacement, opts.maxInflationMm);
    end

    warp = struct();
    warp.displacementMm = displacement(:);
    warp.deltaMm = bsxfun(@times, D, displacement(:));
    warp.normals = N;
    warp.normalOrientation = normalInfo;
    warp.displacementDirections = D;
    warp.directionInfo = directionInfo;
    warp.nearestTraceVertex = nearestIdx(:);
    warp.traceNearestDistanceMm = nearestDist(:);
    warp.traceSignedOffsetMm = signedOffset(:);
    warp.traceSignedOffsetWarpMm = signedOffsetWarp(:);
    warp.traceSignedOffsetNormalMm = signedOffsetNormal(:);
    warp.traceSignedOffsetRadialMm = signedOffsetRadial(:);
    warp.traceUsable = valid(:);
    warp.traceCoverageUsed = coverageValid(:);
    warp.summary = struct( ...
        'nTracePoints', size(tracePoints, 1), ...
        'nUsableTracePoints', nnz(valid), ...
        'nCoverageTracePoints', nnz(coverageValid), ...
        'offsetProjectionMode', opts.offsetProjectionMode, ...
        'seedAggregation', opts.seedAggregation, ...
        'seedPercentile', opts.seedPercentile, ...
        'medianTraceDistanceMm', medianFinite(nearestDist(valid)), ...
        'medianTraceOffsetMm', medianFinite(signedOffset(valid)), ...
        'medianDisplacementMm', medianFinite(displacement(displacement > 0)), ...
        'maxDisplacementMm', max0(displacement));
end

function seedOffset = aggregateSeedOffsets(vertexIdx, offset, nVertex, opts)
    vertexIdx = vertexIdx(:);
    offset = offset(:);
    switch opts.seedAggregation
        case 'median'
            reducer = @median;
        case 'mean'
            reducer = @mean;
        case 'max'
            reducer = @max;
        case 'percentile'
            reducer = @(x) percentileLocal(x, opts.seedPercentile);
        otherwise
            reducer = @median;
    end
    seedOffset = accumarray(vertexIdx, offset, [nVertex 1], reducer, NaN);
end

function signedOffset = chooseSignedOffset(warpOffset, normalOffset, radialOffset, opts)
    switch opts.offsetProjectionMode
        case 'warpDirection'
            signedOffset = warpOffset;
        case 'normal'
            signedOffset = normalOffset;
        case 'radial'
            signedOffset = radialOffset;
        case 'maxWarpRadial'
            signedOffset = max([warpOffset(:), radialOffset(:)], [], 2);
        case 'maxNormalRadial'
            signedOffset = max([normalOffset(:), radialOffset(:)], [], 2);
        case 'maxAll'
            signedOffset = max([warpOffset(:), normalOffset(:), radialOffset(:)], [], 2);
        otherwise
            signedOffset = warpOffset;
    end
end

function [D, info] = prepareWarpDirections(V, N, opts)
    [radialUnit, ~] = radialDirections(V);
    alignment = sum(N .* radialUnit, 2);
    alignment(~isfinite(alignment)) = 0;
    alignment = max(0, alignment);
    info = struct( ...
        'mode', opts.warpDirectionMode, ...
        'radialBlendThreshold', opts.warpRadialBlendThreshold, ...
        'meanRadialWeight', 0, ...
        'maxRadialWeight', 0, ...
        'radialDominantFraction', 0, ...
        'radialDotMedian', medianFinite(alignment), ...
        'globalTraceFlipped', false);

    switch opts.warpDirectionMode
        case 'normal'
            D = N;
        case 'radial'
            D = radialUnit;
            info.meanRadialWeight = 1;
            info.maxRadialWeight = 1;
            info.radialDominantFraction = 1;
        case 'blendRadial'
            if opts.warpRadialBlendThreshold <= 0
                wRadial = zeros(size(alignment));
            else
                wRadial = max(0, min(1, ...
                    (opts.warpRadialBlendThreshold - alignment) ./ ...
                    opts.warpRadialBlendThreshold));
            end
            D = bsxfun(@times, N, 1 - wRadial) + ...
                bsxfun(@times, radialUnit, wRadial);
            D = normalizeRows(D);
            info.meanRadialWeight = meanFinite(wRadial);
            info.maxRadialWeight = max0(wRadial);
            info.radialDominantFraction = nnz(wRadial >= 0.5) ./ ...
                max(1, numel(wRadial));
    end
end

function [radialUnit, info] = radialDirections(V)
    center = median(V, 1);
    radial = bsxfun(@minus, V, center);
    radialMag = sqrt(sum(radial .^ 2, 2));
    valid = isfinite(radialMag) & radialMag > eps;
    radialUnit = zeros(size(radial));
    radialUnit(valid, :) = bsxfun(@rdivide, radial(valid, :), radialMag(valid));
    info = struct('centerMm', center, ...
        'validFraction', nnz(valid) / max(1, size(V, 1)), ...
        'dotMedian', NaN);
end

function [N, info] = prepareWarpNormals(V, N, opts)
    info = struct( ...
        'requestedMode', opts.normalOrientationMode, ...
        'appliedMode', 'none', ...
        'nVertices', size(V, 1), ...
        'nFlipped', 0, ...
        'flipFraction', 0, ...
        'radialOpposedFraction', NaN, ...
        'radialDotMedian', NaN, ...
        'globalTraceFlipped', false, ...
        'allowGlobalTraceFlip', false);

    switch opts.normalOrientationMode
        case 'none'
            return;
        case 'globalTrace'
            info.allowGlobalTraceFlip = true;
            return;
        case {'radial', 'autoRadial'}
            [Nrad, radial] = orientNormalsRadially(V, N);
            info.radialOpposedFraction = radial.opposedFraction;
            info.radialDotMedian = radial.dotMedian;
            useRadial = strcmp(opts.normalOrientationMode, 'radial') || ...
                radial.opposedFraction >= opts.normalRadialFlipThreshold;
            if useRadial
                N = Nrad;
                info.appliedMode = 'radial';
                info.nFlipped = radial.nFlipped;
                info.flipFraction = radial.flipFraction;
            else
                info.allowGlobalTraceFlip = true;
            end
    end
end

function [Nout, info] = orientNormalsRadially(V, N)
    [radialUnit, ~] = radialDirections(V);
    valid = sqrt(sum(radialUnit .^ 2, 2)) > 0;
    radialDot = sum(N .* radialUnit, 2);
    flip = valid & isfinite(radialDot) & radialDot < 0;
    Nout = N;
    Nout(flip, :) = -Nout(flip, :);
    info = struct( ...
        'nFlipped', nnz(flip), ...
        'flipFraction', nnz(flip) / max(1, size(V, 1)), ...
        'opposedFraction', nnz(flip) / max(1, nnz(valid)), ...
        'dotMedian', medianFinite(radialDot(valid)));
end

function displacement = smoothVertexScalars(F, seedOffset, seeded, opts)
    n = numel(seedOffset);
    E = unique(sort([F(:, [1 2]); F(:, [2 3]); F(:, [1 3])], 2), 'rows');
    A = sparse([E(:, 1); E(:, 2)], [E(:, 2); E(:, 1)], 1, n, n);
    deg = full(sum(A, 2));
    deg(deg == 0) = 1;
    displacement = seedOffset;
    for it = 1:opts.smoothingIterations
        neighborMean = full(A * displacement) ./ deg;
        displacement = (1 - opts.smoothingBlend) * displacement + ...
            opts.smoothingBlend * neighborMean;
        if any(seeded)
            displacement(seeded) = opts.seedWeight * seedOffset(seeded) + ...
                (1 - opts.seedWeight) * displacement(seeded);
        end
    end
end

function [Vout, info] = smoothWarpedSurfaceGeometry(F, V, opts)
    Vout = double(V);
    F = double(F);
    n = size(Vout, 1);
    [A, deg, boundary] = meshAdjacency(F, n);
    fixed = false(n, 1);
    if opts.surfaceSmoothingPreserveBoundary
        fixed(boundary) = true;
    end

    roughBefore = vertexRoughnessMm(Vout, A, deg);
    for it = 1:opts.surfaceSmoothingIterations
        Vout = taubinSmoothingStep(Vout, A, deg, fixed, ...
            opts.surfaceSmoothingLambda);
        Vout = taubinSmoothingStep(Vout, A, deg, fixed, ...
            opts.surfaceSmoothingMu);
    end
    roughAfter = vertexRoughnessMm(Vout, A, deg);
    moveMm = sqrt(sum((Vout - double(V)) .^ 2, 2));
    info = struct( ...
        'mode', 'taubin', ...
        'iterations', opts.surfaceSmoothingIterations, ...
        'lambda', opts.surfaceSmoothingLambda, ...
        'mu', opts.surfaceSmoothingMu, ...
        'preserveBoundary', opts.surfaceSmoothingPreserveBoundary, ...
        'preservedBoundaryVertices', nnz(fixed), ...
        'medianMoveMm', medianFinite(moveMm), ...
        'p95MoveMm', percentileLocal(moveMm(isfinite(moveMm)), 95), ...
        'maxMoveMm', max0(moveMm), ...
        'medianRoughnessBeforeMm', medianFinite(roughBefore), ...
        'medianRoughnessAfterMm', medianFinite(roughAfter));
end

function [Vout, info] = repairWarpedSurfaceDents(F, Vsource, Vwarped, opts)
    F = double(F);
    Vsource = double(Vsource);
    Vout = double(Vwarped);
    n = size(Vout, 1);
    [A, deg, boundary] = meshAdjacency(F, n);
    neighbors = adjacencyListFromSparse(A, n);
    medEdge = medianEdgeLengthMm(F, Vout);
    if ~isfinite(medEdge) || medEdge <= 0
        medEdge = max(1, opts.dentRepairRadiusMm);
    end
    nRings = max(1, ceil(opts.dentRepairRadiusMm / medEdge));
    nRings = min(opts.dentRepairMaxRings, nRings);
    fixed = false(n, 1);
    if opts.dentRepairProtectBoundary
        fixed(boundary) = true;
    end

    maxRepairRows = n;
    if opts.dentRepairMaxFlaggedFraction > 0 && ...
            opts.dentRepairMaxFlaggedFraction < 1
        maxRepairRows = max(1, floor(opts.dentRepairMaxFlaggedFraction * n));
    end

    totalMove = zeros(n, 1);
    iterationInfo = repmat(struct( ...
        'iteration', 0, ...
        'nFlagged', 0, ...
        'nRepaired', 0, ...
        'medianMoveMm', 0, ...
        'maxMoveMm', 0, ...
        'p95DentDepthMm', NaN, ...
        'maxDentDepthMm', NaN), max(1, opts.dentRepairIterations), 1);

    initialDiag = dentDiagnosticsForSurface(F, Vout, A, deg, neighbors, ...
        nRings, opts);
    enabled = strcmpi(opts.dentRepairMode, 'auto') && ...
        opts.dentRepairIterations > 0;
    nActualIterations = 0;
    for it = 1:opts.dentRepairIterations
        diag = dentDiagnosticsForSurface(F, Vout, A, deg, neighbors, ...
            nRings, opts);
        candidates = diag.dentMask(:) & ~fixed;
        repairRows = selectWorstDentRows(candidates, ...
            diag.dentDepthMm, maxRepairRows);
        nActualIterations = it;
        iterationInfo(it).iteration = it;
        iterationInfo(it).nFlagged = nnz(candidates);
        iterationInfo(it).nRepaired = numel(repairRows);
        iterationInfo(it).p95DentDepthMm = percentileLocal( ...
            diag.dentDepthMm(isfinite(diag.dentDepthMm)), 95);
        iterationInfo(it).maxDentDepthMm = max0( ...
            diag.dentDepthMm(isfinite(diag.dentDepthMm)));
        if ~enabled || isempty(repairRows)
            if ~enabled
                nActualIterations = 0;
            end
            break;
        end

        requestedMove = opts.dentRepairBlend .* ...
            max(0, diag.dentDepthMm(repairRows));
        remainingMove = max(0, opts.dentRepairMaxMoveMm - ...
            totalMove(repairRows));
        stepMove = min(requestedMove(:), remainingMove(:));
        ok = isfinite(stepMove) & stepMove > 0;
        repairRows = repairRows(ok);
        stepMove = stepMove(ok);
        if isempty(repairRows)
            break;
        end
        Vout(repairRows, :) = Vout(repairRows, :) + ...
            bsxfun(@times, diag.repairDirection(repairRows, :), stepMove);
        totalMove(repairRows) = totalMove(repairRows) + stepMove;
        iterationInfo(it).medianMoveMm = medianFinite(stepMove);
        iterationInfo(it).maxMoveMm = max0(stepMove);
    end

    finalDiag = dentDiagnosticsForSurface(F, Vout, A, deg, neighbors, ...
        nRings, opts);
    if nActualIterations < numel(iterationInfo)
        iterationInfo = iterationInfo(1:max(1, nActualIterations));
    end
    repaired = totalMove > 0;
    repairedRows = find(repaired);
    initialWorstRows = selectWorstDentRows(initialDiag.dentMask, ...
        initialDiag.dentDepthMm, 200);
    finalWorstRows = selectWorstDentRows(finalDiag.dentMask, ...
        finalDiag.dentDepthMm, 200);
    sourceMove = sqrt(sum((Vout - Vsource) .^ 2, 2));
    info = struct( ...
        'mode', opts.dentRepairMode, ...
        'enabled', enabled, ...
        'metric', opts.dentRepairMetric, ...
        'radiusMm', opts.dentRepairRadiusMm, ...
        'neighborhoodRings', nRings, ...
        'medianEdgeLengthMm', medEdge, ...
        'envelopePercentile', opts.dentRepairEnvelopePercentile, ...
        'minDentMm', opts.dentRepairMinDentMm, ...
        'normalAngleDeg', opts.dentRepairNormalAngleDeg, ...
        'localSmoothingIterations', ...
            opts.dentRepairLocalSmoothingIterations, ...
        'directionRadialWeight', opts.dentRepairDirectionRadialWeight, ...
        'blend', opts.dentRepairBlend, ...
        'maxMoveMm', opts.dentRepairMaxMoveMm, ...
        'maxFlaggedFraction', opts.dentRepairMaxFlaggedFraction, ...
        'protectBoundary', opts.dentRepairProtectBoundary, ...
        'preservedBoundaryVertices', nnz(fixed), ...
        'nVerticesFlaggedInitial', nnz(initialDiag.dentMask), ...
        'nVerticesFlaggedFinal', nnz(finalDiag.dentMask), ...
        'nVerticesRepaired', nnz(repaired), ...
        'repairedVertexRows', repairedRows, ...
        'worstDentVertexRowsInitial', initialWorstRows, ...
        'worstDentVertexRowsFinal', finalWorstRows, ...
        'medianRepairMoveMm', medianFinite(totalMove(repaired)), ...
        'p95RepairMoveMm', percentileLocal(totalMove(repaired), 95), ...
        'maxRepairMoveMm', max0(totalMove), ...
        'p95DentDepthBeforeMm', percentileLocal( ...
            initialDiag.dentDepthMm(isfinite(initialDiag.dentDepthMm)), 95), ...
        'maxDentDepthBeforeMm', max0( ...
            initialDiag.dentDepthMm(isfinite(initialDiag.dentDepthMm))), ...
        'p95DentDepthAfterMm', percentileLocal( ...
            finalDiag.dentDepthMm(isfinite(finalDiag.dentDepthMm)), 95), ...
        'maxDentDepthAfterMm', max0( ...
            finalDiag.dentDepthMm(isfinite(finalDiag.dentDepthMm))), ...
        'p95NormalRoughnessBeforeDeg', percentileLocal( ...
            initialDiag.normalRoughnessDeg(isfinite( ...
            initialDiag.normalRoughnessDeg)), 95), ...
        'p95NormalRoughnessAfterDeg', percentileLocal( ...
            finalDiag.normalRoughnessDeg(isfinite( ...
            finalDiag.normalRoughnessDeg)), 95), ...
        'medianSourceDisplacementAfterMm', medianFinite( ...
            sourceMove(sourceMove > 0)), ...
        'maxSourceDisplacementAfterMm', max0(sourceMove), ...
        'iterations', iterationInfo, ...
        'dentDepthMm', finalDiag.dentDepthMm, ...
        'dentMask', finalDiag.dentMask, ...
        'normalRoughnessDeg', finalDiag.normalRoughnessDeg, ...
        'repairMoveMm', totalMove);
end

function diag = dentDiagnosticsForSurface(F, V, A, deg, neighbors, nRings, opts)
    TR = triangulation(F, V);
    Nv = normalizeRows(vertexNormal(TR));
    [Nv, ~] = orientNormalsRadially(V, Nv);
    Ns = smoothNormalsByAdjacencySparse(Nv, A, deg, ...
        max(1, min(8, nRings)));
    normalRoughnessDeg = vectorAnglesDeg(Nv, Ns);
    [radialUnit, radialInfo] = radialDirections(V);
    radialWeight = opts.dentRepairDirectionRadialWeight;
    repairDirection = normalizeRows((1 - radialWeight) .* Ns + ...
        radialWeight .* radialUnit);
    badDir = sqrt(sum(repairDirection .^ 2, 2)) <= eps | ...
        ~all(isfinite(repairDirection), 2);
    repairDirection(badDir, :) = radialUnit(badDir, :);
    Vlocal = smoothPositionsByAdjacencySparse(V, A, deg, ...
        opts.dentRepairLocalSmoothingIterations, 0.65);
    localDelta = Vlocal - V;
    localDentDepth = sum(localDelta .* repairDirection, 2);
    localDentDepth(~isfinite(localDentDepth)) = 0;
    localDentDepth = max(0, localDentDepth);
    center = median(V, 1);
    radial = bsxfun(@minus, V, center);
    radialDistance = sqrt(sum(radial .^ 2, 2));
    if usesRadialEnvelopeDentMetric(opts.dentRepairMetric)
        localEnvelope = localPercentileByRings(neighbors, radialDistance, ...
            nRings, opts.dentRepairEnvelopePercentile);
        radialDentDepth = localEnvelope - radialDistance;
        radialDentDepth(~isfinite(radialDentDepth)) = 0;
        radialDentDepth = max(0, radialDentDepth);
    else
        localEnvelope = radialDistance;
        radialDentDepth = zeros(size(radialDistance));
    end
    switch opts.dentRepairMetric
        case 'radialEnvelope'
            dentDepth = radialDentDepth;
        case 'hybrid'
            dentDepth = max(localDentDepth, min(radialDentDepth, ...
                localDentDepth + opts.dentRepairMinDentMm));
        otherwise
            dentDepth = localDentDepth;
    end
    strongDent = dentDepth >= opts.dentRepairMinDentMm;
    creaseDent = dentDepth >= 0.5 * opts.dentRepairMinDentMm & ...
        normalRoughnessDeg >= opts.dentRepairNormalAngleDeg;
    dentMask = (strongDent | creaseDent) & all(isfinite(V), 2);
    diag = struct( ...
        'centerMm', center, ...
        'metric', opts.dentRepairMetric, ...
        'radialCenterMm', radialInfo.centerMm, ...
        'radialDistanceMm', radialDistance, ...
        'localEnvelopeRadiusMm', localEnvelope, ...
        'radialEnvelopeDentDepthMm', radialDentDepth, ...
        'localLaplacianDentDepthMm', localDentDepth, ...
        'localSmoothedPointsMm', Vlocal, ...
        'repairDirection', repairDirection, ...
        'dentDepthMm', dentDepth, ...
        'dentMask', dentMask, ...
        'normalRoughnessDeg', normalRoughnessDeg, ...
        'vertexRoughnessMm', vertexRoughnessMm(V, A, deg), ...
        'nRings', nRings);
end

function info = refreshDentRepairDiagnostics(F, V, info, opts)
    F = double(F);
    V = double(V);
    n = size(V, 1);
    [A, deg, ~] = meshAdjacency(F, n);
    neighbors = adjacencyListFromSparse(A, n);
    if isfield(info, 'neighborhoodRings') && ...
            isnumeric(info.neighborhoodRings) && isscalar(info.neighborhoodRings)
        nRings = max(1, round(double(info.neighborhoodRings)));
    else
        medEdge = medianEdgeLengthMm(F, V);
        if ~isfinite(medEdge) || medEdge <= 0
            medEdge = max(1, opts.dentRepairRadiusMm);
        end
        nRings = max(1, ceil(opts.dentRepairRadiusMm / medEdge));
        nRings = min(opts.dentRepairMaxRings, nRings);
    end
    diag = dentDiagnosticsForSurface(F, V, A, deg, neighbors, nRings, opts);
    info.postSurfaceSmoothingDiagnostics = true;
    info.nVerticesFlaggedFinal = nnz(diag.dentMask);
    info.worstDentVertexRowsFinal = selectWorstDentRows( ...
        diag.dentMask, diag.dentDepthMm, 200);
    info.p95DentDepthAfterMm = percentileLocal( ...
        diag.dentDepthMm(isfinite(diag.dentDepthMm)), 95);
    info.maxDentDepthAfterMm = max0( ...
        diag.dentDepthMm(isfinite(diag.dentDepthMm)));
    info.p95NormalRoughnessAfterDeg = percentileLocal( ...
        diag.normalRoughnessDeg(isfinite(diag.normalRoughnessDeg)), 95);
    info.dentDepthMm = diag.dentDepthMm;
    info.dentMask = diag.dentMask;
    info.normalRoughnessDeg = diag.normalRoughnessDeg;
end

function tf = usesRadialEnvelopeDentMetric(metric)
    tf = any(strcmpi(metric, {'radialEnvelope', 'hybrid'}));
end

function rows = selectWorstDentRows(mask, dentDepth, maxRows)
    rows = find(mask(:));
    if isempty(rows) || numel(rows) <= maxRows
        return;
    end
    [~, order] = sort(dentDepth(rows), 'descend');
    rows = rows(order(1:maxRows));
end

function Vnext = taubinSmoothingStep(V, A, deg, fixed, step)
    neighborMean = bsxfun(@rdivide, full(A * V), deg);
    delta = neighborMean - V;
    Vnext = V + step .* delta;
    Vnext(fixed, :) = V(fixed, :);
end

function [A, deg, boundaryVertices] = meshAdjacency(F, n)
    Eall = sort([F(:, [1 2]); F(:, [2 3]); F(:, [1 3])], 2);
    [E, ~, ic] = unique(Eall, 'rows');
    counts = accumarray(ic, 1);
    boundaryEdges = E(counts == 1, :);
    boundaryVertices = unique(boundaryEdges(:));
    A = sparse([E(:, 1); E(:, 2)], [E(:, 2); E(:, 1)], ...
        ones(2 * size(E, 1), 1), n, n);
    A = spones(A);
    deg = full(sum(A, 2));
    deg(deg == 0) = 1;
end

function roughness = vertexRoughnessMm(V, A, deg)
    neighborMean = bsxfun(@rdivide, full(A * V), deg);
    roughness = sqrt(sum((V - neighborMean) .^ 2, 2));
end

function neighbors = adjacencyListFromSparse(A, n)
    neighbors = cell(n, 1);
    [ii, jj] = find(A);
    for k = 1:numel(ii)
        neighbors{ii(k)}(end + 1, 1) = jj(k); %#ok<AGROW>
    end
end

function medEdge = medianEdgeLengthMm(F, V)
    E = unique(sort([F(:, [1 2]); F(:, [2 3]); F(:, [1 3])], 2), 'rows');
    if isempty(E)
        medEdge = NaN;
        return;
    end
    edgeLen = sqrt(sum((V(E(:, 1), :) - V(E(:, 2), :)) .^ 2, 2));
    medEdge = medianFinite(edgeLen);
end

function values = localPercentileByRings(neighbors, vertexValue, nRings, pct)
    n = numel(vertexValue);
    values = nan(n, 1);
    for i = 1:n
        rows = neighborRowsWithinRings(neighbors, i, nRings);
        x = vertexValue(rows);
        x = x(isfinite(x));
        if isempty(x)
            values(i) = vertexValue(i);
        else
            values(i) = percentileLocal(x, pct);
        end
    end
end

function rows = neighborRowsWithinRings(neighbors, startRow, nRings)
    rows = startRow(:);
    frontier = rows;
    for r = 1:nRings
        newRows = gatherNeighborRows(neighbors, frontier);
        if isempty(newRows)
            break;
        end
        newRows = newRows(~ismember(newRows, rows));
        if isempty(newRows)
            break;
        end
        rows = unique([rows; newRows]); %#ok<AGROW>
        frontier = newRows;
    end
end

function rows = gatherNeighborRows(neighbors, sourceRows)
    buckets = cell(numel(sourceRows), 1);
    for i = 1:numel(sourceRows)
        buckets{i} = neighbors{sourceRows(i)};
    end
    if isempty(buckets)
        rows = [];
    else
        rows = unique(vertcat(buckets{:}));
    end
end

function N = smoothNormalsByAdjacencySparse(N, A, deg, nIter)
    N = normalizeRows(N);
    for it = 1:nIter
        neighbor = bsxfun(@rdivide, full(A * N), deg);
        flip = sum(neighbor .* N, 2) < 0;
        neighbor(flip, :) = -neighbor(flip, :);
        N = normalizeRows(0.5 * N + 0.5 * neighbor);
    end
end

function Vout = smoothPositionsByAdjacencySparse(V, A, deg, nIter, blend)
    Vout = double(V);
    if nIter <= 0
        return;
    end
    blend = max(0, min(1, double(blend)));
    for it = 1:nIter
        neighbor = bsxfun(@rdivide, full(A * Vout), deg);
        Vout = (1 - blend) .* Vout + blend .* neighbor;
    end
end

function [capDelta, info] = interpolateDeltaToCapMesh(fitPoints, fitDelta, capPoints, opts)
    k = min(opts.interpK, size(fitPoints, 1));
    idx = zeros(size(capPoints, 1), k);
    d2 = zeros(size(capPoints, 1), k);
    chunk = 1200;
    for a = 1:chunk:size(capPoints, 1)
        b = min(size(capPoints, 1), a + chunk - 1);
        D = squaredDistanceRows(capPoints(a:b, :), fitPoints);
        [sortedD, order] = sort(D, 2, 'ascend');
        idx(a:b, :) = order(:, 1:k);
        d2(a:b, :) = sortedD(:, 1:k);
    end
    W = exp(-0.5 * d2 ./ (opts.interpSigmaMm .^ 2));
    Wsum = sum(W, 2);
    Wsum(Wsum == 0) = 1;
    capDelta = zeros(size(capPoints));
    for j = 1:k
        capDelta = capDelta + bsxfun(@times, fitDelta(idx(:, j), :), W(:, j));
    end
    capDelta = bsxfun(@rdivide, capDelta, Wsum);
    info = struct('mode', 'gaussianNearestFitMesh', ...
        'k', k, 'sigmaMm', opts.interpSigmaMm, ...
        'medianNearestMm', medianFinite(sqrt(d2(:, 1))));
end

function roastOut = makeWarpedRoastMask(skin, TRfitWarped, opts)
    if isempty(opts.roastMaskFile)
        error('acsWarpScalpSurfaceToPolhemusTrace:MissingRoastMask', ...
            'makeRoastMask requires roastMaskFile.');
    end
    if exist(opts.roastMaskFile, 'file') ~= 2
        error('acsWarpScalpSurfaceToPolhemusTrace:RoastMaskNotFound', ...
            'ROAST mask file not found: %s', opts.roastMaskFile);
    end
    if isempty(opts.roastMaskOutputFile)
        [folder, stem] = fileparts(opts.roastMaskFile);
        opts.roastMaskOutputFile = fullfile(folder, [stem '_' opts.outputTag '.nii']);
    end
    if exist(opts.roastMaskOutputFile, 'file') == 2 && ~opts.force
        roastOut = struct('maskFile', opts.roastMaskOutputFile, ...
            'didWriteMask', false, 'message', 'existing mask reused');
        return;
    end
    if ~isfield(skin, 'meta') || isempty(skin.meta)
        error('acsWarpScalpSurfaceToPolhemusTrace:MissingSkinMeta', ...
            'ROAST mask writing requires capMaker skin meta transforms.');
    end
    Vmask = spm_vol(opts.roastMaskFile);
    Vmask = Vmask(1);
    labels = uint8(round(spm_read_vols(Vmask)));
    [labels, preWarpSkinCleanup] = cleanupWarpedRoastSkinComponents( ...
        labels, labels, opts);
    labelsBeforeWarp = labels;
    if isfield(skin, 'fitCoordinateFrame') && ...
            strcmpi(skin.fitCoordinateFrame, 'capMakerPreCropWorldMm')
        oldVox = stableWorldMmToVoxel1(skin.fit.Points, skin.meta);
        newVox = stableWorldMmToVoxel1(TRfitWarped.Points, skin.meta);
        coordinateMapping = 'capMakerPreCropWorldMm_to_originalMriVoxel';
    else
        oldFitPrint = skin.fit.Points;
        newFitPrint = TRfitWarped.Points;
        oldVox = printMmToVoxel1(oldFitPrint, skin.meta);
        newVox = printMmToVoxel1(newFitPrint, skin.meta);
        coordinateMapping = 'capMakerPrintMm_to_originalMriVoxel';
    end
    voxelSize = sqrt(sum(Vmask.mat(1:3, 1:3) .^ 2, 1));
    voxelSize = voxelSize(isfinite(voxelSize) & voxelSize > 0);
    if isempty(voxelSize)
        stepVox = 1;
    else
        stepVox = opts.voxelSampleStepMm / min(voxelSize);
    end
    if opts.verbose
        fprintf('Voxelizing warped ROAST skin with %s.\n', ...
            opts.roastSkinVoxelMode);
    end
    voxelTic = tic;
    [voxelRows, skinVoxelization] = warpedSkinVoxelRows( ...
        TRfitWarped.ConnectivityList, oldVox, newVox, Vmask.mat, ...
        size(labels), stepVox, labelsBeforeWarp, opts);
    skinVoxelization.elapsedSeconds = toc(voxelTic);
    if opts.verbose
        fprintf('Voxelized warped ROAST skin in %.1f s.\n', ...
            skinVoxelization.elapsedSeconds);
    end
    voxelRows = clipVoxelRows(voxelRows, size(labels));
    if isempty(voxelRows)
        lin = zeros(0, 1);
        overwrite = false(0, 1);
    else
        lin = sub2ind(size(labels), voxelRows(:, 1), voxelRows(:, 2), voxelRows(:, 3));
        overwrite = ismember(labels(lin), uint8(opts.roastOverwriteLabels));
        labels(lin(overwrite)) = uint8(5);
    end
    [labels, skinCleanup] = cleanupWarpedRoastSkinComponents( ...
        labels, labelsBeforeWarp, opts);

    writeLabelNifti(opts.roastMaskOutputFile, Vmask, labels, ...
        'ACS scalp-trace warped ROAST hard labels');

    t1Out = '';
    if opts.makeRoastT1Copy
        if isempty(opts.roastT1File)
            error('acsWarpScalpSurfaceToPolhemusTrace:MissingRoastT1', ...
                'makeRoastT1Copy requires roastT1File.');
        end
        if isempty(opts.roastT1OutputFile)
            [folder, maskStem] = fileparts(opts.roastMaskOutputFile);
            t1Stem = regexprep(maskStem, '_T1orT2_SPM_masks.*$', '');
            t1Out = fullfile(folder, [t1Stem '.nii']);
        else
            t1Out = opts.roastT1OutputFile;
        end
        if exist(t1Out, 'file') ~= 2 || opts.force
            copyfile(opts.roastT1File, t1Out);
        end
    end

    roastOut = struct();
    roastOut.maskFile = opts.roastMaskOutputFile;
    roastOut.t1File = t1Out;
    roastOut.didWriteMask = true;
    roastOut.nVoxelsMarkedSkin = nnz(overwrite);
    roastOut.allowedOverwriteLabels = opts.roastOverwriteLabels;
    roastOut.coordinateMapping = coordinateMapping;
    skinVoxelization.nCandidateVoxelsAfterClipping = size(voxelRows, 1);
    skinVoxelization.nVoxelsMarkedSkin = roastOut.nVoxelsMarkedSkin;
    roastOut.skinVoxelization = skinVoxelization;
    roastOut.preWarpSkinCleanup = preWarpSkinCleanup;
    roastOut.skinCleanup = skinCleanup;
end

function [rows, info] = warpedSkinVoxelRows(F, oldVox, newVox, mat, dims, ...
        stepVox, labelsBeforeWarp, opts)
    info = struct('mode', opts.roastSkinVoxelMode, ...
        'preExpansionVoxelCount', 0, ...
        'postExpansionVoxelCount', 0, ...
        'closedSurfaceCandidateVoxels', 0, ...
        'nCandidateVoxelsAfterClipping', 0, ...
        'nVoxelsMarkedSkin', 0, ...
        'fallbackMode', '', ...
        'message', '');
    info.surfaceVoxelDiagnostics = surfaceVoxelDiagnostics(oldVox, newVox, mat);
    switch opts.roastSkinVoxelMode
        case 'rasterSurfaceFill'
            [rows, rasterInfo] = rasterSurfaceFillVoxels( ...
                F, newVox, mat, dims, stepVox, labelsBeforeWarp, opts);
            info.rasterSurface = rasterInfo;
            if isempty(rows)
                warning('acsWarpScalpSurfaceToPolhemusTrace:RasterSurfaceFillEmpty', ...
                    ['Rasterized surface fill returned no voxels; falling ', ...
                     'back to surface-neighborhood voxelization.']);
                rows = surfaceSampleVoxels(F, newVox, stepVox, opts, ...
                    'raster-fill fallback surface');
                info.fallbackMode = 'surfaceNeighborhood';
            end
        case 'closedSurfaceFill'
            [rows, closedInfo] = closedSurfaceFillVoxels(F, newVox, dims, opts);
            info.closedSurfaceCandidateVoxels = size(rows, 1);
            info.closedSurface = closedInfo;
            if isempty(rows)
                warning('acsWarpScalpSurfaceToPolhemusTrace:ClosedSurfaceFillEmpty', ...
                    ['Closed-surface skin voxelization returned no voxels; ', ...
                     'falling back to surface-neighborhood voxelization.']);
                rows = surfaceSampleVoxels(F, newVox, stepVox, opts, ...
                    'closed-fill fallback surface');
                info.fallbackMode = 'surfaceNeighborhood';
            end
        case 'surfaceNeighborhood'
            rows = surfaceSampleVoxels(F, newVox, stepVox, opts, ...
                'surface-neighborhood skin');
        case 'sweptSegments'
            rows = sampledSegmentVoxels(oldVox, newVox, stepVox, opts, ...
                'legacy swept skin segments');
        otherwise
            rows = surfaceSampleVoxels(F, newVox, stepVox, opts, ...
                'fallback surface-neighborhood skin');
            info.fallbackMode = 'surfaceNeighborhood';
            info.message = 'unrecognized mode after parsing';
    end
    rows = unique(round(rows), 'rows');
    info.preExpansionVoxelCount = size(rows, 1);
    if any(strcmp(opts.roastSkinVoxelMode, ...
            {'closedSurfaceFill', 'rasterSurfaceFill'})) && ...
            isempty(info.fallbackMode)
        if opts.skinVoxelRadiusMm > 0
            surfaceRows = surfaceSampleVoxels(F, newVox, stepVox, opts, ...
                'warped skin surface padding');
            surfaceRows = expandVoxelRows(surfaceRows, mat, ...
                opts.skinVoxelRadiusMm, opts, 'warped skin surface padding');
            rows = unique([rows; surfaceRows], 'rows');
        end
    else
        rows = expandVoxelRows(rows, mat, opts.skinVoxelRadiusMm, opts, ...
            sprintf('%s voxel expansion', opts.roastSkinVoxelMode));
    end
    info.postExpansionVoxelCount = size(rows, 1);
end

function [rows, info] = rasterSurfaceFillVoxels(F, V, mat, dims, stepVox, ...
        labelsBeforeWarp, opts)
    info = struct('usedImfill', false, ...
        'shellVoxelCount', 0, ...
        'baseHeadVoxelCount', 0, ...
        'filledVoxelCount', 0, ...
        'gapVoxelCount', 0, ...
        'interiorVoxelCount', 0, ...
        'sliceFillCounts', [0 0 0], ...
        'boundingBoxMin', [nan nan nan], ...
        'boundingBoxMax', [nan nan nan], ...
        'reason', '');
    rows = zeros(0, 3);
    if exist('imfill', 'file') ~= 2
        info.reason = 'imfill unavailable';
        warning('acsWarpScalpSurfaceToPolhemusTrace:MissingImfill', ...
            ['imfill is unavailable; raster-surface fill cannot be used ', ...
             'for warped ROAST skin voxelization.']);
        return;
    end
    logProgress(opts, '  raster fill: sampling warped surface shell.\n');
    shellRows = surfaceSampleVoxels(F, V, stepVox, opts, ...
        'raster warped skin surface');
    logProgress(opts, '  raster fill: expanding surface shell by %.2f mm.\n', ...
        opts.skinVoxelRadiusMm);
    shellRows = expandVoxelRows(shellRows, mat, opts.skinVoxelRadiusMm, ...
        opts, 'raster surface shell expansion');
    shellRows = clipVoxelRows(shellRows, dims);
    shellRows = unique(round(shellRows), 'rows');
    info.shellVoxelCount = size(shellRows, 1);
    if isempty(shellRows)
        info.reason = 'empty rasterized surface shell';
        return;
    end

    margin = 2;
    lo = max([1 1 1], min(shellRows, [], 1) - margin);
    hi = min(double(dims), max(shellRows, [], 1) + margin);
    info.boundingBoxMin = lo;
    info.boundingBoxMax = hi;
    localDims = hi - lo + 1;
    if any(localDims <= 0) || any(~isfinite(localDims))
        info.reason = 'invalid local bounding box';
        return;
    end
    localRows = bsxfun(@minus, shellRows, lo) + 1;
    shell = false(localDims);
    lin = sub2ind(localDims, localRows(:, 1), localRows(:, 2), localRows(:, 3));
    shell(lin) = true;
    localLabels = labelsBeforeWarp(lo(1):hi(1), lo(2):hi(2), lo(3):hi(3));
    baseHead = localLabels > 0;
    info.baseHeadVoxelCount = nnz(baseHead);

    logProgress(opts, ['  raster fill: slice-filling local shell volume ', ...
        '[%d %d %d] voxels.\n'], localDims(1), localDims(2), localDims(3));
    try
        [filledShell, sliceCounts] = fillShellSlicesAllAxes(shell, opts);
    catch ME
        warning('acsWarpScalpSurfaceToPolhemusTrace:RasterSurfaceFillFailed', ...
            'Raster surface slice-fill failed: %s', ME.message);
        info.reason = ME.message;
        rows = shellRows;
        return;
    end
    filled = filledShell | baseHead;
    idx = find(filled);
    [i, j, k] = ind2sub(size(filled), idx);
    rows = [i j k] + lo - 1;
    info.usedImfill = true;
    info.sliceFillCounts = sliceCounts;
    info.filledVoxelCount = size(rows, 1);
    info.gapVoxelCount = nnz(filled & ~baseHead);
    info.interiorVoxelCount = nnz(filledShell & ~shell);
    if info.gapVoxelCount == info.shellVoxelCount
        info.reason = 'slice fill added no gap voxels beyond the surface shell';
    end
    logProgress(opts, ['  raster fill: filled %d voxels, including %d ', ...
        'gap/shell voxels outside original labels.\n'], ...
        info.filledVoxelCount, info.gapVoxelCount);
end

function [filled, counts] = fillShellSlicesAllAxes(shell, opts)
    fills = false([size(shell) 3]);
    counts = zeros(1, 3);
    fills(:, :, :, 1) = fillShellSlicesOneAxis(shell, 3, opts, 'axial');
    counts(1) = nnz(fills(:, :, :, 1));
    fills(:, :, :, 2) = fillShellSlicesOneAxis(shell, 2, opts, 'coronal');
    counts(2) = nnz(fills(:, :, :, 2));
    fills(:, :, :, 3) = fillShellSlicesOneAxis(shell, 1, opts, 'sagittal');
    counts(3) = nnz(fills(:, :, :, 3));
    voteCount = sum(fills, 4);
    filled = voteCount >= 1;
end

function filled = fillShellSlicesOneAxis(shell, dim, opts, label)
    order = [setdiff(1:3, dim, 'stable') dim];
    S = permute(shell, order);
    filledPerm = false(size(S));
    nSlices = size(S, 3);
    progressEnabled = progressIsVerbose(opts) && nSlices >= 10;
    nextPct = 25;
    if progressEnabled
        fprintf('  raster fill %s slices: 0%% (%d slices)\n', label, nSlices);
    end
    for i = 1:nSlices
        sl = S(:, :, i);
        if any(sl(:))
            filledPerm(:, :, i) = imfill(sl, 'holes');
        end
        if progressEnabled
            pct = floor(100 * i / nSlices);
            if pct >= nextPct
                fprintf('  raster fill %s slices: %d%% (%d/%d)\n', ...
                    label, min(pct, 100), i, nSlices);
                nextPct = nextPct + 25;
            end
        end
    end
    filled = ipermute(filledPerm, order);
end

function [rows, info] = closedSurfaceFillVoxels(F, V, dims, opts)
    info = struct('usedInpolyhedron', false, ...
        'boundingBoxMin', [nan nan nan], ...
        'boundingBoxMax', [nan nan nan], ...
        'queryVoxelCount', 0, ...
        'insideVoxelCount', 0, ...
        'reason', '');
    rows = zeros(0, 3);
    if exist('inpolyhedron', 'file') ~= 2
        info.reason = 'inpolyhedron unavailable';
        warning('acsWarpScalpSurfaceToPolhemusTrace:MissingInpolyhedron', ...
            ['inpolyhedron is unavailable; closed-surface fill cannot be ', ...
             'used for warped ROAST skin voxelization.']);
        return;
    end
    F = double(F);
    V = double(V);
    finiteRows = all(isfinite(V), 2);
    if nnz(finiteRows) < 4 || isempty(F)
        info.reason = 'empty or nonfinite mesh';
        return;
    end
    validFaceIndex = all(isfinite(F), 2) & ...
        all(F >= 1 & F <= size(V, 1), 2);
    F = F(validFaceIndex, :);
    validVertex = false(size(V, 1), 1);
    validVertex(finiteRows) = true;
    validFaces = all(validVertex(F), 2);
    F = F(validFaces, :);
    if isempty(F)
        info.reason = 'no finite faces';
        return;
    end
    usedVertices = unique(F(:));
    Vf = V(usedVertices, :);
    margin = 2;
    lo = max([1 1 1], floor(min(Vf, [], 1)) - margin);
    hi = min(double(dims), ceil(max(Vf, [], 1)) + margin);
    if any(~isfinite(lo)) || any(~isfinite(hi)) || any(hi < lo)
        info.reason = 'invalid mesh bounds';
        return;
    end
    lo = round(lo);
    hi = round(hi);
    info.boundingBoxMin = lo;
    info.boundingBoxMax = hi;
    x = lo(1):hi(1);
    y = lo(2):hi(2);
    z = lo(3):hi(3);
    info.queryVoxelCount = numel(x) * numel(y) * numel(z);
    if info.queryVoxelCount == 0
        info.reason = 'empty bounding box';
        return;
    end

    Nf = faceNormalsLocal(F, V);
    rowsCell = cell(numel(z), 1);
    [X, Y] = ndgrid(x, y);
    xy = [X(:) Y(:)];
    progressEnabled = progressIsVerbose(opts) && numel(z) >= 10;
    nextPct = 10;
    if progressEnabled
        fprintf('  closed fill point-in-mesh: 0%% (%d z-slices)\n', numel(z));
    end
    for zi = 1:numel(z)
        points = [xy repmat(z(zi), size(xy, 1), 1)];
        inside = inpolyhedron(F, V, points, 'facenormals', Nf, 'tol', 1e-9);
        if any(inside)
            rowsCell{zi} = points(inside, :);
        else
            rowsCell{zi} = zeros(0, 3);
        end
        if progressEnabled
            pct = floor(100 * zi / numel(z));
            if pct >= nextPct
                fprintf('  closed fill point-in-mesh: %d%% (%d/%d)\n', ...
                    min(pct, 100), zi, numel(z));
                nextPct = nextPct + 10;
            end
        end
    end
    rows = vertcat(rowsCell{:});
    rows = unique(round(rows), 'rows');
    info.usedInpolyhedron = true;
    info.insideVoxelCount = size(rows, 1);
    if isempty(rows)
        info.reason = 'no inside voxels';
    end
end

function rows = surfaceSampleVoxels(F, V, stepVox, opts, label)
    if nargin < 4 || isempty(opts)
        opts = struct('verbose', false);
    end
    if nargin < 5 || isempty(label)
        label = 'surface sampling';
    end
    F = double(F);
    V = double(V);
    if isempty(F) || isempty(V)
        rows = zeros(0, 3);
        return;
    end
    logProgress(opts, '  %s: collecting vertices/faces.\n', label);
    rows = round(V);
    edges = unique(sort([F(:, [1 2]); F(:, [2 3]); F(:, [1 3])], 2), 'rows');
    if ~isempty(edges)
        logProgress(opts, '  %s: sampling %d mesh edges.\n', ...
            label, size(edges, 1));
        rows = [rows; sampledSegmentVoxels(V(edges(:, 1), :), ...
            V(edges(:, 2), :), stepVox, opts, [label ' edges'])]; %#ok<AGROW>
    end
    logProgress(opts, '  %s: adding face centroids and edge midpoints.\n', label);
    centroids = (V(F(:, 1), :) + V(F(:, 2), :) + V(F(:, 3), :)) ./ 3;
    edgeMid = [ ...
        (V(F(:, 1), :) + V(F(:, 2), :)) ./ 2; ...
        (V(F(:, 2), :) + V(F(:, 3), :)) ./ 2; ...
        (V(F(:, 1), :) + V(F(:, 3), :)) ./ 2];
    rows = unique(round([rows; centroids; edgeMid]), 'rows');
    logProgress(opts, '  %s: %d unique surface voxels.\n', ...
        label, size(rows, 1));
end

function Nf = faceNormalsLocal(F, V)
    A = V(F(:, 1), :);
    B = V(F(:, 2), :);
    C = V(F(:, 3), :);
    Nf = cross(B - A, C - A, 2);
    n = sqrt(sum(Nf .^ 2, 2));
    n(n == 0 | ~isfinite(n)) = 1;
    Nf = Nf ./ n;
end

function info = surfaceVoxelDiagnostics(oldVox, newVox, mat)
    voxelSize = sqrt(sum(mat(1:3, 1:3) .^ 2, 1));
    voxelSize(~isfinite(voxelSize) | voxelSize <= 0) = 1;
    oldKeep = all(isfinite(oldVox), 2);
    newKeep = all(isfinite(newVox), 2);
    info = struct('oldCenterVoxel', [nan nan nan], ...
        'newCenterVoxel', [nan nan nan], ...
        'centerShiftVoxel', [nan nan nan], ...
        'centerShiftMmApprox', [nan nan nan], ...
        'oldBoundsVoxel', nan(2, 3), ...
        'newBoundsVoxel', nan(2, 3), ...
        'voxelSizeMm', voxelSize);
    if any(oldKeep)
        info.oldCenterVoxel = mean(oldVox(oldKeep, :), 1);
        info.oldBoundsVoxel = [min(oldVox(oldKeep, :), [], 1); ...
            max(oldVox(oldKeep, :), [], 1)];
    end
    if any(newKeep)
        info.newCenterVoxel = mean(newVox(newKeep, :), 1);
        info.newBoundsVoxel = [min(newVox(newKeep, :), [], 1); ...
            max(newVox(newKeep, :), [], 1)];
    end
    info.centerShiftVoxel = info.newCenterVoxel - info.oldCenterVoxel;
    info.centerShiftMmApprox = info.centerShiftVoxel .* voxelSize;
end

function logProgress(opts, varargin)
    if progressIsVerbose(opts)
        fprintf(varargin{:});
    end
end

function tf = progressIsVerbose(opts)
    tf = isstruct(opts) && isfield(opts, 'verbose') && logical(opts.verbose);
end

function vox1 = printMmToVoxel1(pointsPrintMm, meta)
    finalWorldMm = applyAffineToPoints(meta.print.T_print2world, pointsPrintMm);
    mriWorldMm = (meta.align.R \ finalWorldMm')';
    voxel0 = applyAffineToPoints(inv(meta.original.vox2world), mriWorldMm);
    vox1 = voxel0 + 1;
end

function vox1 = stableWorldMmToVoxel1(pointsStableMm, meta)
    voxel0 = applyAffineToPoints(inv(meta.original.vox2world), pointsStableMm);
    vox1 = voxel0 + 1;
end

function rows = sampledSegmentVoxels(P0, P1, stepVox, opts, label)
    if nargin < 4 || isempty(opts)
        opts = struct('verbose', false);
    end
    if nargin < 5 || isempty(label)
        label = 'segment sampling';
    end
    rows = zeros(0, 3);
    dist = sqrt(sum((P1 - P0) .^ 2, 2));
    active = find(isfinite(dist) & dist > 0.05)';
    nActive = numel(active);
    progressEnabled = progressIsVerbose(opts) && nActive >= 500;
    nextPct = 10;
    if progressEnabled
        fprintf('  %s: 0%% (%d segments)\n', label, nActive);
    end
    for ii = 1:nActive
        i = active(ii);
        n = max(2, ceil(dist(i) / stepVox) + 1);
        t = linspace(0, 1, n)';
        P = (1 - t) .* P0(i, :) + t .* P1(i, :);
        rows = [rows; round(P)]; %#ok<AGROW>
        if progressEnabled
            pct = floor(100 * ii / nActive);
            if pct >= nextPct
                fprintf('  %s: %d%% (%d/%d)\n', ...
                    label, min(pct, 100), ii, nActive);
                nextPct = nextPct + 10;
            end
        end
    end
    if isempty(rows)
        rows = round(P1);
    end
    rows = unique(rows, 'rows');
end

function rows = expandVoxelRows(rows, mat, radiusMm, opts, label)
    if nargin < 4 || isempty(opts)
        opts = struct('verbose', false);
    end
    if nargin < 5 || isempty(label)
        label = 'voxel expansion';
    end
    if isempty(rows) || radiusMm <= 0
        return;
    end
    voxelSize = sqrt(sum(mat(1:3, 1:3) .^ 2, 1));
    voxelSize = voxelSize(isfinite(voxelSize) & voxelSize > 0);
    if isempty(voxelSize)
        voxelSize = 1;
    end
    maxOff = ceil(radiusMm ./ min(voxelSize));
    offsets = [];
    for i = -maxOff:maxOff
        for j = -maxOff:maxOff
            for k = -maxOff:maxOff
                deltaMm = norm([i j k] .* voxelSize);
                if deltaMm <= radiusMm
                    offsets(end + 1, :) = [i j k]; %#ok<AGROW>
                end
            end
        end
    end
    expanded = zeros(size(rows, 1) * size(offsets, 1), 3);
    pos = 0;
    progressEnabled = progressIsVerbose(opts) && size(offsets, 1) >= 20;
    nextPct = 25;
    if progressEnabled
        fprintf('  %s: 0%% (%d offsets)\n', label, size(offsets, 1));
    end
    for i = 1:size(offsets, 1)
        n = size(rows, 1);
        expanded(pos + (1:n), :) = rows + offsets(i, :);
        pos = pos + n;
        if progressEnabled
            pct = floor(100 * i / size(offsets, 1));
            if pct >= nextPct
                fprintf('  %s: %d%% (%d/%d)\n', ...
                    label, min(pct, 100), i, size(offsets, 1));
                nextPct = nextPct + 25;
            end
        end
    end
    rows = unique(expanded, 'rows');
end

function rows = clipVoxelRows(rows, dims)
    keep = rows(:, 1) >= 1 & rows(:, 1) <= dims(1) & ...
        rows(:, 2) >= 1 & rows(:, 2) <= dims(2) & ...
        rows(:, 3) >= 1 & rows(:, 3) <= dims(3);
    rows = rows(keep, :);
end

function [labels, info] = cleanupWarpedRoastSkinComponents( ...
        labels, labelsBeforeWarp, opts)
    skin = labels == 5;
    info = struct('enabled', opts.cleanupRoastSkinComponents, ...
        'mode', opts.roastSkinCleanupMode, ...
        'componentCountBefore', 0, ...
        'keptComponentCount', 0, ...
        'removedComponentCount', 0, ...
        'largestComponentVoxels', 0, ...
        'removedSkinVoxels', 0, ...
        'reason', '');
    if ~opts.cleanupRoastSkinComponents
        info.reason = 'cleanupRoastSkinComponents=false';
        return;
    end
    if nnz(skin) == 0
        info.reason = 'no skin voxels';
        return;
    end
    if exist('bwconncomp', 'file') ~= 2
        warning('acsWarpScalpSurfaceToPolhemusTrace:MissingBwconncomp', ...
            ['bwconncomp is not available, so disconnected warped-skin ', ...
             'cleanup was skipped.']);
        info.reason = 'bwconncomp unavailable';
        return;
    end

    CC = bwconncomp(skin, 26);
    sizes = cellfun(@numel, CC.PixelIdxList);
    info.componentCountBefore = CC.NumObjects;
    if isempty(sizes)
        info.reason = 'no connected components';
        return;
    end
    [largestSize, largestIdx] = max(sizes);
    info.largestComponentVoxels = largestSize;
    switch opts.roastSkinCleanupMode
        case 'largest'
            keepComponents = largestIdx;
        case 'minSize'
            keepComponents = find(sizes >= opts.minRoastSkinComponentVoxels);
            if isempty(keepComponents)
                keepComponents = largestIdx;
            end
        otherwise
            keepComponents = largestIdx;
    end

    keep = false(size(skin));
    for i = keepComponents(:)'
        keep(CC.PixelIdxList{i}) = true;
    end
    remove = skin & ~keep;
    restoreLabels = labelsBeforeWarp;
    restoreLabels(restoreLabels == 5) = uint8(0);
    labels(remove) = restoreLabels(remove);

    info.keptComponentCount = numel(keepComponents);
    info.removedComponentCount = CC.NumObjects - numel(keepComponents);
    info.removedSkinVoxels = nnz(remove);
    if info.removedSkinVoxels == 0
        info.reason = 'no disconnected skin components removed';
    else
        info.reason = 'removed disconnected warped-skin components';
    end
end

