function [meta, metaFile] = traceSourceMeta(trace, fallbackMeta)
    meta = fallbackMeta;
    metaFile = '';
    if ~isfield(trace, 'source') || isempty(trace.source) || ...
            ~isstruct(trace.source)
        return;
    end
    candidates = {};
    if isfield(trace.source, 'cacheFile') && ~isempty(trace.source.cacheFile)
        candidates{end + 1} = trace.source.cacheFile; %#ok<AGROW>
    end
    if isfield(trace.source, 'file') && ~isempty(trace.source.file)
        candidates{end + 1} = trace.source.file; %#ok<AGROW>
    end
    for i = 1:numel(candidates)
        fileName = expandUserPath(char(candidates{i}));
        if exist(fileName, 'file') ~= 2
            continue;
        end
        S = load(fileName, 'meta');
        if isfield(S, 'meta') && ~isempty(S.meta)
            meta = S.meta;
            metaFile = fileName;
            return;
        end
    end
end

