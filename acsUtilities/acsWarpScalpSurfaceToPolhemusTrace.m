    end
    tf = any(strcmpi(char(x), {'traceSetName', 'outputFile', 'outputTag', ...
        'force', 'inflateOnly', 'maxTraceDistanceMm', 'maxInflationMm', ...
        'displacementScale', 'normalOrientationMode', ...
        'normalRadialFlipThreshold', 'warpDirectionMode', ...
        'warpRadialBlendThreshold', 'offsetProjectionMode', ...
        'robustUpperPercentile', ...
        'influenceRadiusMm', 'influenceSigmaMm', ...
        'coverageOffsetToleranceMm', ...
        'smoothingIterations', 'smoothingBlend', ...
        'surfaceSmoothingIterations', 'surfaceSmoothingLambda', ...
        'surfaceSmoothingMu', 'surfaceSmoothingPreserveBoundary', ...
        'dentRepairMode', 'dentRepairMetric', 'dentRepairIterations', ...
        'dentRepairRadiusMm', 'dentRepairEnvelopePercentile', ...
        'dentRepairMinDentMm', 'dentRepairNormalAngleDeg', ...
        'dentRepairLocalSmoothingIterations', ...
        'dentRepairDirectionRadialWeight', ...
        'dentRepairBlend', 'dentRepairMaxMoveMm', ...
        'dentRepairMaxRings', 'dentRepairMaxFlaggedFraction', ...
        'dentRepairProtectBoundary', 'seedWeight', ...
        'seedAggregation', 'seedPercentile', ...
        'interpK', 'interpSigmaMm', 'makeRoastMask', ...
        'roastMaskFile', 'roastMaskOutputFile', 'roastT1File', ...
        'makeRoastT1Copy', 'roastT1OutputFile', ...
        'roastSkinVoxelMode', 'skinVoxelRadiusMm', ...
        'voxelSampleStepMm', 'roastOverwriteLabels', ...
        'cleanupRoastSkinComponents', 'roastSkinCleanupMode', ...
        'minRoastSkinComponentVoxels', 'showFigures', 'saveFigures', ...
        'verbose'}));
end

function mode = normalizeNormalOrientationMode(mode)
    mode = lower(strtrim(char(mode)));
    mode = regexprep(mode, '[\s_\-]+', '');
    switch mode
        case {'globaltrace', 'trace', 'legacy'}
            mode = 'globalTrace';
        case {'autoradial', 'auto', 'radialauto'}
            mode = 'autoRadial';
        case {'radial', 'centroid', 'centerout'}
            mode = 'radial';
        case {'none', 'raw'}
            mode = 'none';
        otherwise
