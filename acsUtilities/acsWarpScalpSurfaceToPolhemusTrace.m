function [idx, dist] = nearestRows(reference, query, chunk)
    idx = zeros(size(query, 1), 1);
    dist = zeros(size(query, 1), 1);
    for a = 1:chunk:size(query, 1)
        b = min(size(query, 1), a + chunk - 1);
        D = squaredDistanceRows(query(a:b, :), reference);
        [d2, idxLocal] = min(D, [], 2);
        idx(a:b) = idxLocal;
        dist(a:b) = sqrt(d2);
    end
end

function dist = minDistanceToRows(query, reference, chunk)
    dist = inf(size(query, 1), 1);
    for a = 1:chunk:size(query, 1)
        b = min(size(query, 1), a + chunk - 1);
        D = squaredDistanceRows(query(a:b, :), reference);
        dist(a:b) = sqrt(min(D, [], 2));
    end
end

function D = squaredDistanceRows(A, B)
    D = bsxfun(@plus, sum(A .^ 2, 2), sum(B .^ 2, 2)') - 2 * (A * B');
    D(D < 0) = 0;
end

function angleDeg = vectorAnglesDeg(A, B)
    A = normalizeRows(A);
    B = normalizeRows(B);
    c = sum(A .* B, 2);
    c = max(-1, min(1, c));
    angleDeg = acosd(c);
end

function N = normalizeRows(N)
    mag = sqrt(sum(N .^ 2, 2));
    mag(mag == 0 | ~isfinite(mag)) = 1;
    N = bsxfun(@rdivide, N, mag);
end

