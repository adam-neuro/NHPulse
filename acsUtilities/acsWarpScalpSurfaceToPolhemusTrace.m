    if isempty(hit)
        containsHit = find(contains(lower(names), lower(requestedName)), 1);
        hit = containsHit;
    end
    if isempty(hit)
        error('acsWarpScalpSurfaceToPolhemusTrace:TraceSetNotFound', ...
            'Could not find traceSetName "%s". Available: %s', ...
            requestedName, strjoin(names, ', '));
    end
