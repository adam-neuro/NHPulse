function S = loadStructFile(fileName)
    fileName = expandUserPath(fileName);
    [~, ~, ext] = fileparts(fileName);
    switch lower(ext)
        case '.mat'
            raw = load(fileName);
            S = firstStruct(raw);
        case '.json'
            S = jsondecode(fileread(fileName));
        otherwise
            error('acsWarpScalpSurfaceToPolhemusTrace:UnsupportedTraceFile', ...
                'Trace input file must be MAT or JSON: %s', fileName);
    end
end

function S = firstStruct(raw)
    preferred = {'out', 'outForSave', 'registration', 'modelFiducials'};
    for i = 1:numel(preferred)
        if isfield(raw, preferred{i}) && isstruct(raw.(preferred{i}))
            S = raw.(preferred{i});
            return;
        end
    end
    names = fieldnames(raw);
    for i = 1:numel(names)
        if isstruct(raw.(names{i}))
            S = raw.(names{i});
            return;
        end
    end
    error('acsWarpScalpSurfaceToPolhemusTrace:NoStructInFile', ...
        'Could not find a readable struct in file.');
end

