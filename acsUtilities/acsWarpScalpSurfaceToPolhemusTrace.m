function [skin, source] = readSkinSource(surfaceOrTrace, traceIn)
    sourceCandidate = surfaceOrTrace;
    if isTraceOverlay(surfaceOrTrace) && isfield(surfaceOrTrace, 'meshSource')
        sourceCandidate = surfaceOrTrace.meshSource;
    elseif isempty(surfaceOrTrace) && isTraceOverlay(traceIn) && ...
            isfield(traceIn, 'meshSource')
        sourceCandidate = traceIn.meshSource;
    end
    [S, source] = loadSkinCacheStruct(sourceCandidate);
    if ~isfield(S, 'TRskin') || isempty(S.TRskin)
        error('acsWarpScalpSurfaceToPolhemusTrace:MissingTRskin', ...
            'Skin cache/source does not contain TRskin.');
    end
    skin = struct();
    skin.cap = ensureTriangulation(S.TRskin);
    skin.meta = getOptionalField(S, 'meta', struct());
    skin.fitIsCap = true;
    skin.capCoordinateFrame = 'capMakerPrintMm';
    skin.fitCoordinateFrame = 'capMakerPrintMm';
    if isfield(S, 'TRstableHead') && ~isempty(S.TRstableHead)
        skin.fit = ensureTriangulation(S.TRstableHead);
        skin.fitIsCap = false;
        skin.fitCoordinateFrame = 'capMakerPreCropWorldMm';
    elseif isfield(S, 'meta') && isstruct(S.meta) && ...
            isfield(S.meta, 'stableHead') && ...
            isstruct(S.meta.stableHead) && ...
            isfield(S.meta.stableHead, 'TR') && ...
            ~isempty(S.meta.stableHead.TR)
        skin.fit = ensureTriangulation(S.meta.stableHead.TR);
        skin.fitIsCap = false;
        skin.fitCoordinateFrame = 'capMakerPreCropWorldMm';
    elseif isfield(S, 'TRfiducialHead') && ~isempty(S.TRfiducialHead)
        skin.fit = ensureTriangulation(S.TRfiducialHead);
        skin.fitIsCap = false;
    elseif isfield(S, 'meta') && isstruct(S.meta) && ...
            isfield(S.meta, 'fiducialHead') && ...
            isstruct(S.meta.fiducialHead) && ...
            isfield(S.meta.fiducialHead, 'TR') && ...
            ~isempty(S.meta.fiducialHead.TR)
        skin.fit = ensureTriangulation(S.meta.fiducialHead.TR);
        skin.fitIsCap = false;
    else
        skin.fit = skin.cap;
    end
