function lim = colorLimitsPositive(values)
    values = double(values(:));
    values = values(isfinite(values));
    if isempty(values)
        lim = [0 1];
        return;
    end
    hi = percentileLocal(values(values > 0), 99.5);
    if ~isfinite(hi) || hi <= 0
        hi = max(values);
    end
    if ~isfinite(hi) || hi <= 0
        hi = 1;
    end
    lim = [0 hi];
end

