function out = acsWarpScalpSurfaceToPolhemusTrace(surfaceOrTrace, traceIn, varargin)
% ACSWARPSCALPSURFACETOPOLHEMUSTRACE Fit a scalp mesh to registered Polhemus trace points.
%
% out = acsWarpScalpSurfaceToPolhemusTrace(traceQc) uses the output from
% acsVisualizePolhemusTraceOnHead. The utility estimates outward
% displacement from a capMaker full-head/cap skin mesh toward registered
% Polhemus scalp trace samples, smooths that displacement on the surface,
% and writes a derived skin-mesh cache. The original cache is not modified.
%
% out = acsWarpScalpSurfaceToPolhemusTrace(surfaceSource, traceQc) lets the
% mesh source be supplied explicitly. surfaceSource may be a layout, skin
% cache, model fiducial report, triangulation, or MAT file containing TRskin.
%
% Optional ROAST support: when roastMaskFile is supplied and makeRoastMask is
% true, the function writes a derived hard-label mask in ROAST label order by
% updating label 5 (skin) from the warped outer scalp surface. By default the
% warped mask is generated by rasterizing and filling the closed warped
% surface; the slower inpolyhedron fill and legacy old-to-warped segment
% sweep remain available as named options.
%
% Name-value options:
%   traceSetName             : trace set/object name to use ['']
%   outputFile               : warped skin cache MAT file ['']
%   outputTag                : file/report tag ['scalpTraceWarp']
%   force                    : overwrite existing outputs [false]
%   inflateOnly              : disallow inward surface displacement [true]
%   maxTraceDistanceMm       : reject trace samples farther than this [35]
%   maxInflationMm           : cap surface displacement [18]
%   displacementScale        : multiply accepted trace offsets [1]
%   normalOrientationMode    : 'globalTrace', 'autoRadial', 'radial', or 'none' ['globalTrace']
%   normalRadialFlipThreshold : radial-opposed fraction for autoRadial [0.02]
%   warpDirectionMode        : 'normal', 'blendRadial', or 'radial' ['normal']
%   warpRadialBlendThreshold : normal/radial alignment threshold for blendRadial [0.35]
%   offsetProjectionMode     : 'warpDirection', 'radial', or 'maxWarpRadial' ['warpDirection']
%   robustUpperPercentile    : cap using trace offset percentile [99]
%   influenceRadiusMm        : zero warp far from trace samples [35]
%   influenceSigmaMm         : Gaussian trace-distance falloff [[]]
%   coverageOffsetToleranceMm : near-zero/inward samples still count as local coverage [0.5]
%   smoothingIterations      : surface Laplacian smoothing iterations [35]
%   smoothingBlend           : neighbor blend per iteration [0.55]
%   surfaceSmoothingIterations : post-warp Taubin mesh smoothing iterations [0]
%   surfaceSmoothingLambda   : post-warp smoothing forward step [0.35]
%   surfaceSmoothingMu       : post-warp smoothing reverse step [-0.37]
%   surfaceSmoothingPreserveBoundary : keep open-boundary vertices fixed [true]
%   dentRepairMode           : 'off', 'diagnose', or 'auto' ['off']
%   dentRepairMetric         : 'localLaplacian', 'radialEnvelope', or 'hybrid' ['localLaplacian']
%   dentRepairIterations     : outward repair passes for local dents [2]
%   dentRepairRadiusMm       : neighborhood radius used to define local envelope [8]
%   dentRepairEnvelopePercentile : local radial envelope percentile [75]
%   dentRepairMinDentMm      : minimum inward radial dent depth [2]
%   dentRepairNormalAngleDeg : normal roughness threshold for shallow creases [35]
%   dentRepairLocalSmoothingIterations : local surface smoothing scale [3]
%   dentRepairDirectionRadialWeight : radial contribution to repair direction [0.25]
%   dentRepairBlend          : fraction of dent depth repaired per pass [0.85]
%   dentRepairMaxMoveMm      : maximum repair move per vertex [8]
%   dentRepairMaxRings       : cap adjacency rings for neighborhood search [8]
%   dentRepairMaxFlaggedFraction : cap repaired vertices per pass [0.15]
%   dentRepairProtectBoundary : keep open-boundary vertices fixed [true]
%   seedWeight               : keep trace-constrained vertices near data [0.85]
%   seedAggregation          : per-vertex trace seed reducer ['median']
%   seedPercentile           : percentile for seedAggregation='percentile' [75]
%   interpK                  : full-head-to-cap interpolation neighbors [6]
%   interpSigmaMm            : full-head-to-cap interpolation sigma [12]
%   makeRoastMask            : write derived ROAST hard-label mask [false]
%   roastMaskFile            : source ROAST T1orT2_SPM_masks.nii ['']
%   roastMaskOutputFile      : output warped hard-label mask ['']
%   roastT1File              : source T1 used by ROAST ['']
%   makeRoastT1Copy          : write copied T1 with matching warped stem [false]
%   roastT1OutputFile        : output copied T1 filename ['']
%   roastSkinVoxelMode       : 'rasterSurfaceFill', 'closedSurfaceFill', 'surfaceNeighborhood', or 'sweptSegments' ['rasterSurfaceFill']
%   skinVoxelRadiusMm        : skin voxel marking radius around samples [0.8]
%   voxelSampleStepMm        : step along old-to-warped surface segments [0.5]
%   roastOverwriteLabels     : labels allowed to become skin [[0 5 6]]
%   cleanupRoastSkinComponents : remove disconnected skin islands [true]
%   roastSkinCleanupMode     : 'largest' or 'minSize' ['largest']
%   minRoastSkinComponentVoxels : min component size for minSize mode [1000]
%   showFigures              : show QC figure [false]
%   saveFigures              : save QC figure [false]
%   verbose                  : print summary [true]

    if nargin < 1 || isempty(surfaceOrTrace)
        error('acsWarpScalpSurfaceToPolhemusTrace:MissingInput', ...
            'Provide a trace QC/registration output or a surface source.');
    end
    if nargin < 2
        traceIn = [];
    elseif isNameValueStart(traceIn)
        varargin = [{traceIn}, varargin];
        traceIn = [];
    end

    opts = parseInputs(varargin{:});
    addLocalDependencies();

    if isempty(traceIn)
        traceIn = surfaceOrTrace;
    end

    [skin, source] = readSkinSource(surfaceOrTrace, traceIn);
    trace = readTracePoints(traceIn, opts);
    if isempty(trace.coordinatesMm)
        error('acsWarpScalpSurfaceToPolhemusTrace:NoTracePoints', ...
            'No trace points were found in the supplied Polhemus input.');
    end
    trace.originalCoordinatesMm = trace.coordinatesMm;
    [trace.coordinatesMm, traceFrameInfo] = traceCoordinatesForFitFrame( ...
        trace, skin);
    if isfield(trace, 'excludedCoordinatesMm') && ...
            ~isempty(trace.excludedCoordinatesMm)
        excludedTrace = trace;
        excludedTrace.coordinatesMm = trace.excludedCoordinatesMm;
        trace.excludedOriginalCoordinatesMm = trace.excludedCoordinatesMm;
        trace.excludedCoordinatesMm = traceCoordinatesForFitFrame( ...
            excludedTrace, skin);
    end
    trace.coordinateFrame = skin.fitCoordinateFrame;
    trace.frameTransform = traceFrameInfo;

    opts = resolveOutputPaths(source, opts);
    if exist(opts.outputFile, 'file') == 2 && ~opts.force
        reportFile = defaultReportFile(opts.outputFile);
        if exist(reportFile, 'file') == 2
            S = load(reportFile);
            out = firstStruct(S);
        else
            out = struct('createdOn', char(datetime('now')), ...
                'outputFile', opts.outputFile, ...
                'reusedExistingCache', true);
        end
        if opts.verbose
            fprintf('Warped scalp cache already exists; reusing %s\n', opts.outputFile);
        end
        return;
    end

    fitTR = skin.fit;
    capTR = skin.cap;
    fitWarp = estimateSurfaceWarp(fitTR, trace.coordinatesMm, opts);
    TRfitWarped = triangulation(fitTR.ConnectivityList, ...
        fitTR.Points + fitWarp.deltaMm);
    if ~strcmpi(opts.dentRepairMode, 'off')
        if opts.verbose
            fprintf('Running post-warp dent diagnostics/repair (%s).\n', ...
                opts.dentRepairMode);
        end
        [VfitRepaired, dentRepair] = repairWarpedSurfaceDents( ...
            TRfitWarped.ConnectivityList, fitTR.Points, ...
            TRfitWarped.Points, opts);
        if opts.verbose
            fprintf(['Finished post-warp dent repair: %d -> %d flags, ', ...
                '%d vertices repaired.\n'], ...
                dentRepair.nVerticesFlaggedInitial, ...
                dentRepair.nVerticesFlaggedFinal, ...
                dentRepair.nVerticesRepaired);
        end
        fitWarp.preDentRepairDisplacementMm = fitWarp.displacementMm;
        fitWarp.deltaMm = VfitRepaired - fitTR.Points;
        fitWarp.displacementMm = sqrt(sum(fitWarp.deltaMm .^ 2, 2));
        fitWarp.summary.medianDisplacementMm = medianFinite( ...
            fitWarp.displacementMm(fitWarp.displacementMm > 0));
        fitWarp.summary.maxDisplacementMm = max0(fitWarp.displacementMm);
        fitWarp.dentRepair = dentRepair;
        TRfitWarped = triangulation(TRfitWarped.ConnectivityList, ...
            VfitRepaired);
    else
        fitWarp.dentRepair = struct( ...
            'mode', 'off', ...
            'enabled', false, ...
            'nVerticesRepaired', 0);
    end
    if opts.surfaceSmoothingIterations > 0
        [VfitSmoothed, surfaceSmoothing] = smoothWarpedSurfaceGeometry( ...
            TRfitWarped.ConnectivityList, TRfitWarped.Points, opts);
        fitWarp.preSurfaceSmoothingDisplacementMm = fitWarp.displacementMm;
        fitWarp.deltaMm = VfitSmoothed - fitTR.Points;
        fitWarp.displacementMm = sqrt(sum(fitWarp.deltaMm .^ 2, 2));
        fitWarp.summary.medianDisplacementMm = medianFinite( ...
            fitWarp.displacementMm(fitWarp.displacementMm > 0));
        fitWarp.summary.maxDisplacementMm = max0(fitWarp.displacementMm);
        fitWarp.surfaceSmoothing = surfaceSmoothing;
        TRfitWarped = triangulation(TRfitWarped.ConnectivityList, VfitSmoothed);
        if isfield(fitWarp, 'dentRepair') && ...
                isstruct(fitWarp.dentRepair) && ...
                ~strcmpi(fitWarp.dentRepair.mode, 'off')
            fitWarp.dentRepair = refreshDentRepairDiagnostics( ...
                TRfitWarped.ConnectivityList, TRfitWarped.Points, ...
                fitWarp.dentRepair, opts);
        end
    else
        fitWarp.surfaceSmoothing = struct( ...
            'mode', 'none', ...
            'iterations', 0, ...
            'preservedBoundaryVertices', 0);
    end

    if skin.fitIsCap
        TRskin = TRfitWarped;
        capDelta = fitWarp.deltaMm;
        capInterp = struct('mode', 'direct', 'k', 1, 'sigmaMm', 0);
    else
        capPointsFit = capPointsInFitFrame(capTR.Points, skin);
        [capDelta, capInterp] = interpolateDeltaToCapMesh( ...
            fitTR.Points, fitWarp.deltaMm, capPointsFit, opts);
        capDeltaPrint = vectorFromFitToPrintFrame(capDelta, skin);
        TRskin = triangulation(capTR.ConnectivityList, ...
            capTR.Points + capDeltaPrint);
        capDelta = capDeltaPrint;
    end

    TRstableHead = [];
    if strcmpi(skin.fitCoordinateFrame, 'capMakerPreCropWorldMm')
        TRstableHead = TRfitWarped;
        TRfiducialHead = triangulation(TRfitWarped.ConnectivityList, ...
            stableWorldToPrintMm(TRfitWarped.Points, skin.meta));
    else
        TRfiducialHead = TRfitWarped;
    end
    meta = skin.meta;
    meta.scalpWarp = makeWarpMeta(source, trace, fitWarp, capInterp, opts);
    if ~isempty(TRstableHead)
        meta.stableHead.available = true;
        meta.stableHead.cacheVariable = 'TRstableHead';
        meta.stableHead.coordinateFrame = 'capMakerPreCropWorldMm';
        meta.stableHead.description = 'Warped full-head scalp mesh before cap crop/print transform.';
        meta.stableHead.pointCount = size(TRstableHead.Points, 1);
        meta.stableHead.faceCount = size(TRstableHead.ConnectivityList, 1);
    end
    cacheInfo = struct( ...
        'source', source, ...
        'trace', trace, ...
        'fitWarp', stripLargeWarpFields(fitWarp), ...
        'capInterpolation', capInterp, ...
        'createdOn', char(datetime('now')));

    ensureDir(fileparts(opts.outputFile));
    save(opts.outputFile, 'TRskin', 'TRfiducialHead', 'meta', ...
        'TRstableHead', 'cacheInfo', '-v7.3');

    roastOut = struct();
    if opts.makeRoastMask
        roastOut = makeWarpedRoastMask(skin, TRfitWarped, opts);
    end

    fig = [];
    qcFile = '';
    if opts.showFigures || opts.saveFigures
        figVisible = 'off';
        if opts.showFigures
            figVisible = 'on';
        end
        fig = makeQcFigure(fitTR, TRfitWarped, trace, fitWarp, ...
            source, opts, figVisible);
        if opts.saveFigures
            qcFile = fullfile(fileparts(opts.outputFile), 'qc', ...
                [stripMatExtension(getFileName(opts.outputFile)) '_qc.png']);
            ensureDir(fileparts(qcFile));
            saveQcFigure(fig, qcFile);
        end
        if ~opts.showFigures
            close(fig);
            fig = [];
        end
    end

    out = struct();
    out.createdOn = char(datetime('now'));
    out.outputFile = opts.outputFile;
    out.qcFigure = qcFile;
    out.source = source;
    out.trace = trace;
    out.mesh = struct( ...
        'TRskin', TRskin, ...
        'TRfiducialHead', TRfiducialHead, ...
        'TRstableHead', TRstableHead, ...
        'fitCoordinateFrame', skin.fitCoordinateFrame);
    out.meshStats = struct( ...
        'sourceCap', meshStats(capTR), ...
        'sourceFit', meshStats(fitTR), ...
        'warpedCap', meshStats(TRskin), ...
        'warpedFullHead', meshStats(TRfiducialHead), ...
        'warpedStableHead', meshStats(TRstableHead));
    out.warp = stripLargeWarpFields(fitWarp);
    out.capInterpolation = capInterp;
    out.roast = roastOut;
    out.options = opts;
    out.figure = fig;

    outForSave = out;
    if isfield(outForSave, 'figure')
        outForSave = rmfield(outForSave, 'figure');
    end
    if isfield(outForSave, 'mesh')
        outForSave = rmfield(outForSave, 'mesh');
    end
    save(defaultReportFile(opts.outputFile), 'outForSave', '-v7.3');

    if opts.verbose
        printSummary(out);
    end
end

function opts = parseInputs(varargin)
    p = inputParser;
    p.FunctionName = 'acsWarpScalpSurfaceToPolhemusTrace';
    addParameter(p, 'traceSetName', '', @(x) ischar(x) || isstring(x));
    addParameter(p, 'outputFile', '', @(x) ischar(x) || isstring(x));
    addParameter(p, 'outputTag', 'scalpTraceWarp', @(x) ischar(x) || isstring(x));
    addParameter(p, 'force', false, @isBoolLike);
    addParameter(p, 'inflateOnly', true, @isBoolLike);
    addParameter(p, 'maxTraceDistanceMm', 35, @isPositiveScalar);
    addParameter(p, 'maxInflationMm', 18, @isPositiveScalar);
    addParameter(p, 'displacementScale', 1, @isPositiveScalar);
    addParameter(p, 'normalOrientationMode', 'globalTrace', ...
        @(x) ischar(x) || isstring(x));
    addParameter(p, 'normalRadialFlipThreshold', 0.02, @isUnitScalar);
    addParameter(p, 'warpDirectionMode', 'normal', ...
        @(x) ischar(x) || isstring(x));
    addParameter(p, 'warpRadialBlendThreshold', 0.35, @isUnitScalar);
    addParameter(p, 'offsetProjectionMode', 'warpDirection', ...
        @(x) ischar(x) || isstring(x));
    addParameter(p, 'robustUpperPercentile', 99, @isPercentScalar);
    addParameter(p, 'influenceRadiusMm', 35, @isPositiveScalar);
    addParameter(p, 'influenceSigmaMm', [], @(x) isempty(x) || isPositiveScalar(x));
    addParameter(p, 'coverageOffsetToleranceMm', 0.5, @isNonnegativeScalar);
    addParameter(p, 'smoothingIterations', 35, @isNonnegativeScalar);
    addParameter(p, 'smoothingBlend', 0.55, @isUnitScalar);
    addParameter(p, 'surfaceSmoothingIterations', 0, @isNonnegativeScalar);
    addParameter(p, 'surfaceSmoothingLambda', 0.35, @isFiniteScalar);
    addParameter(p, 'surfaceSmoothingMu', -0.37, @isFiniteScalar);
    addParameter(p, 'surfaceSmoothingPreserveBoundary', true, @isBoolLike);
    addParameter(p, 'dentRepairMode', 'off', @(x) ischar(x) || isstring(x));
    addParameter(p, 'dentRepairMetric', 'localLaplacian', ...
        @(x) ischar(x) || isstring(x));
    addParameter(p, 'dentRepairIterations', 2, @isNonnegativeScalar);
    addParameter(p, 'dentRepairRadiusMm', 8, @isPositiveScalar);
    addParameter(p, 'dentRepairEnvelopePercentile', 75, @isPercentScalar);
    addParameter(p, 'dentRepairMinDentMm', 2, @isNonnegativeScalar);
    addParameter(p, 'dentRepairNormalAngleDeg', 35, @isNonnegativeScalar);
    addParameter(p, 'dentRepairLocalSmoothingIterations', 3, ...
        @isNonnegativeScalar);
    addParameter(p, 'dentRepairDirectionRadialWeight', 0.25, @isUnitScalar);
    addParameter(p, 'dentRepairBlend', 0.85, @isUnitScalar);
    addParameter(p, 'dentRepairMaxMoveMm', 8, @isPositiveScalar);
    addParameter(p, 'dentRepairMaxRings', 8, ...
        @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x >= 1);
    addParameter(p, 'dentRepairMaxFlaggedFraction', 0.15, @isUnitScalar);
    addParameter(p, 'dentRepairProtectBoundary', true, @isBoolLike);
    addParameter(p, 'seedWeight', 0.85, @isUnitScalar);
    addParameter(p, 'seedAggregation', 'median', @(x) ischar(x) || isstring(x));
    addParameter(p, 'seedPercentile', 75, @isPercentScalar);
    addParameter(p, 'interpK', 6, @(x) isnumeric(x) && isscalar(x) && x >= 1);
    addParameter(p, 'interpSigmaMm', 12, @isPositiveScalar);
    addParameter(p, 'makeRoastMask', false, @isBoolLike);
    addParameter(p, 'roastMaskFile', '', @(x) ischar(x) || isstring(x));
    addParameter(p, 'roastMaskOutputFile', '', @(x) ischar(x) || isstring(x));
    addParameter(p, 'roastT1File', '', @(x) ischar(x) || isstring(x));
    addParameter(p, 'makeRoastT1Copy', false, @isBoolLike);
    addParameter(p, 'roastT1OutputFile', '', @(x) ischar(x) || isstring(x));
    addParameter(p, 'roastSkinVoxelMode', 'rasterSurfaceFill', ...
        @(x) ischar(x) || isstring(x));
    addParameter(p, 'skinVoxelRadiusMm', 0.8, @isNonnegativeScalar);
    addParameter(p, 'voxelSampleStepMm', 0.5, @isPositiveScalar);
    addParameter(p, 'roastOverwriteLabels', [0 5 6], ...
        @(x) isnumeric(x) && isvector(x));
    addParameter(p, 'cleanupRoastSkinComponents', true, @isBoolLike);
    addParameter(p, 'roastSkinCleanupMode', 'largest', ...
        @(x) ischar(x) || isstring(x));
    addParameter(p, 'minRoastSkinComponentVoxels', 1000, ...
        @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x >= 0);
    addParameter(p, 'showFigures', false, @isBoolLike);
    addParameter(p, 'saveFigures', false, @isBoolLike);
    addParameter(p, 'verbose', true, @isBoolLike);
    parse(p, varargin{:});

    opts = p.Results;
    opts.traceSetName = char(opts.traceSetName);
    opts.outputFile = expandUserPath(char(opts.outputFile));
    opts.outputTag = safeName(char(opts.outputTag));
    opts.force = logical(opts.force);
    opts.inflateOnly = logical(opts.inflateOnly);
    opts.maxTraceDistanceMm = double(opts.maxTraceDistanceMm);
    opts.maxInflationMm = double(opts.maxInflationMm);
    opts.displacementScale = double(opts.displacementScale);
    opts.normalOrientationMode = normalizeNormalOrientationMode( ...
        opts.normalOrientationMode);
    opts.normalRadialFlipThreshold = double(opts.normalRadialFlipThreshold);
    opts.warpDirectionMode = normalizeWarpDirectionMode(opts.warpDirectionMode);
    opts.warpRadialBlendThreshold = double(opts.warpRadialBlendThreshold);
    opts.offsetProjectionMode = normalizeOffsetProjectionMode( ...
        opts.offsetProjectionMode);
    opts.robustUpperPercentile = double(opts.robustUpperPercentile);
    opts.influenceRadiusMm = double(opts.influenceRadiusMm);
    if isempty(opts.influenceSigmaMm)
        opts.influenceSigmaMm = 0.5 * opts.influenceRadiusMm;
    else
        opts.influenceSigmaMm = double(opts.influenceSigmaMm);
    end
    opts.coverageOffsetToleranceMm = double(opts.coverageOffsetToleranceMm);
    opts.smoothingIterations = round(double(opts.smoothingIterations));
    opts.smoothingBlend = double(opts.smoothingBlend);
    opts.surfaceSmoothingIterations = round(double( ...
        opts.surfaceSmoothingIterations));
    opts.surfaceSmoothingLambda = double(opts.surfaceSmoothingLambda);
    opts.surfaceSmoothingMu = double(opts.surfaceSmoothingMu);
    opts.surfaceSmoothingPreserveBoundary = logical( ...
        opts.surfaceSmoothingPreserveBoundary);
    opts.dentRepairMode = normalizeDentRepairMode(opts.dentRepairMode);
    opts.dentRepairIterations = round(double(opts.dentRepairIterations));
    opts.dentRepairRadiusMm = double(opts.dentRepairRadiusMm);
    opts.dentRepairEnvelopePercentile = double( ...
        opts.dentRepairEnvelopePercentile);
    opts.dentRepairMinDentMm = double(opts.dentRepairMinDentMm);
    opts.dentRepairNormalAngleDeg = double(opts.dentRepairNormalAngleDeg);
    opts.dentRepairBlend = double(opts.dentRepairBlend);
    opts.dentRepairMaxMoveMm = double(opts.dentRepairMaxMoveMm);
    opts.dentRepairMaxRings = round(double(opts.dentRepairMaxRings));
    opts.dentRepairMaxFlaggedFraction = double( ...
        opts.dentRepairMaxFlaggedFraction);
    opts.dentRepairProtectBoundary = logical(opts.dentRepairProtectBoundary);
    opts.dentRepairMetric = normalizeDentRepairMetric( ...
        opts.dentRepairMetric);
    opts.dentRepairLocalSmoothingIterations = round(double( ...
        opts.dentRepairLocalSmoothingIterations));
    opts.dentRepairDirectionRadialWeight = double( ...
        opts.dentRepairDirectionRadialWeight);
    opts.seedWeight = double(opts.seedWeight);
    opts.seedAggregation = normalizeSeedAggregation(opts.seedAggregation);
    opts.seedPercentile = double(opts.seedPercentile);
    opts.interpK = round(double(opts.interpK));
    opts.interpSigmaMm = double(opts.interpSigmaMm);
    opts.makeRoastMask = logical(opts.makeRoastMask);
    opts.roastMaskFile = expandUserPath(char(opts.roastMaskFile));
    opts.roastMaskOutputFile = expandUserPath(char(opts.roastMaskOutputFile));
    opts.roastT1File = expandUserPath(char(opts.roastT1File));
    opts.makeRoastT1Copy = logical(opts.makeRoastT1Copy);
    opts.roastT1OutputFile = expandUserPath(char(opts.roastT1OutputFile));
    opts.roastSkinVoxelMode = normalizeRoastSkinVoxelMode( ...
        opts.roastSkinVoxelMode);
    opts.skinVoxelRadiusMm = double(opts.skinVoxelRadiusMm);
    opts.voxelSampleStepMm = double(opts.voxelSampleStepMm);
    opts.roastOverwriteLabels = unique(round(double(opts.roastOverwriteLabels(:))))';
    opts.cleanupRoastSkinComponents = logical(opts.cleanupRoastSkinComponents);
    opts.roastSkinCleanupMode = normalizeRoastSkinCleanupMode( ...
        opts.roastSkinCleanupMode);
    opts.minRoastSkinComponentVoxels = round(double( ...
        opts.minRoastSkinComponentVoxels));
    opts.showFigures = logical(opts.showFigures);
    opts.saveFigures = logical(opts.saveFigures);
    opts.verbose = logical(opts.verbose);
end

