function cls = tracePointClasses(trace, warp, opts)
    n = size(trace.coordinatesMm, 1);
    usable = false(n, 1);
    if isfield(warp, 'traceUsable') && ~isempty(warp.traceUsable)
        m = min(n, numel(warp.traceUsable));
        usable(1:m) = logical(warp.traceUsable(1:m));
    end
    dist = nan(n, 1);
    if isfield(warp, 'traceNearestDistanceMm') && ...
            ~isempty(warp.traceNearestDistanceMm)
        m = min(n, numel(warp.traceNearestDistanceMm));
        dist(1:m) = double(warp.traceNearestDistanceMm(1:m));
    end
    signedOffset = nan(n, 1);
    if isfield(warp, 'traceSignedOffsetMm') && ...
            ~isempty(warp.traceSignedOffsetMm)
        m = min(n, numel(warp.traceSignedOffsetMm));
        signedOffset(1:m) = double(warp.traceSignedOffsetMm(1:m));
    end
    tooFar = ~usable & isfinite(dist) & dist > opts.maxTraceDistanceMm;
    inward = ~usable & ~tooFar & isfinite(signedOffset) & signedOffset <= 0;
    other = ~usable & ~tooFar & ~inward;
    cls = struct('usable', usable, ...
        'rejected', ~usable, ...
        'tooFar', tooFar, ...
        'inward', inward, ...
        'other', other, ...
        'dist', dist, ...
        'signedOffset', signedOffset);
end

