function [pointsOut, info] = traceCoordinatesForFitFrame(trace, skin)
    pointsIn = trace.coordinatesMm;
    inputFrame = traceCoordinateFrame(trace);
    info = struct('from', inputFrame, ...
        'to', skin.fitCoordinateFrame, 'method', 'identity', ...
        'sourceMetaFile', '');
    if strcmpi(inputFrame, skin.fitCoordinateFrame)
        pointsOut = pointsIn;
    elseif strcmpi(skin.fitCoordinateFrame, 'capMakerPreCropWorldMm') && ...
            strcmpi(inputFrame, 'capMakerPrintMm')
        [meta, metaFile] = traceSourceMeta(trace, skin.meta);
        pointsOut = printMmToStableWorld(pointsIn, meta);
        info.method = 'trace-source print-to-pre-crop world via skin metadata';
        info.sourceMetaFile = metaFile;
    elseif strcmpi(skin.fitCoordinateFrame, 'capMakerPrintMm') && ...
            strcmpi(inputFrame, 'capMakerPreCropWorldMm')
        pointsOut = stableWorldToPrintMm(pointsIn, skin.meta);
        info.method = 'trace pre-crop world to capMaker print via skin metadata';
    else
        error('acsWarpScalpSurfaceToPolhemusTrace:FrameMismatch', ...
            ['Trace points are in "%s", but the fitting surface is in "%s". ', ...
             'No conversion path is implemented for this pair.'], ...
            inputFrame, skin.fitCoordinateFrame);
    end
end

