%% ACS ROAST/capMaker Example Walkthrough
% This is the public-facing walkthrough for the current ACS ROAST/capMaker
% workflow. It is designed to be run one cell at a time from the MATLAB
% editor. It keeps the main working path and removes most recovery/debug
% branches from the private development scratch workflow.
%
% High-level pipeline:
%   1. Import and segment a subject MRI.
%   2. Build a ROAST-derived full-head scalp mesh.
%   3. Register a phone scan to the MRI/capMaker frame.
%   4. Warp the shared scalp mesh toward the phone scan and crop it for
%      cap manufacturing.
%   5. Define headpost, ear/face, and chamber exclusion zones.
%   6. Build ROAST-compatible labels using the warped skin and titanium
%      headpost.
%   7. Generate an initial tES lead field, optimize a sparse montage, and
%      grow the candidate layout.
%   8. Add EEG positions and export capMaker manufacturing STLs.
%
% Large MRI, phone-scan, lead-field, and manufacturing products are not stored
% in git. See docs/example_data.md before trying to make a public dataset.
%
% ROAST credit: this workflow builds on ROAST. Please cite ROAST and the
% relevant targeting papers listed in CITATION.md when using this code.
%
% Safety note: this is research software, not a medical device. Inspect all
% intermediate geometry and simulation outputs before manufacturing or use.

