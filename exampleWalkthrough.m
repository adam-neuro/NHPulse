clear restoreFigureWindowStyle;

function opts = baseCapTargetOptions(cfg)
    if nargin < 1
        cfg = struct();
    end
    opts = struct();
    opts.placementMode = 'surfaceVoronoi';
    opts.edgeMarginMM = getFieldOrDefault(cfg, 'layoutEdgeMarginMm', 4);
    opts.bedMarginMM = getFieldOrDefault(cfg, 'layoutBedMarginMm', 2);
    opts.bottomFaceBandMM = 1.5;
    opts.normalUpDotMin = getFieldOrDefault(cfg, 'layoutNormalUpDotMin', 0.2);
    opts.normalMode = 'smooth';
    opts.normalSmoothRadiusMM = 6;
    opts.visibleFromAbove = false;
    opts.preferSymmetry = false;
    opts.midlineMarginMM = 0;
    opts.voronoiIterations = 5;
    opts.voronoiToleranceMM = 0.25;
    opts.voronoiSnapMode = 'spacingAware';
    opts.voronoiSpacingWeight = 4;
    opts.voronoiMinSpacingFraction = 0.65;
    opts.voronoiSpacingIterations = 2;
    opts.voronoiMaxCandidatesPerCell = 60;
    opts.vizSurfaceGeodesic = false;
    opts.vizSurfaceVoronoi = false;
end

function opts = addHeadpostKeepout(opts, headpostExclusion)
    if isempty(headpostExclusion) || ~isstruct(headpostExclusion)
        return;
    end
    center = [];
    if isfield(headpostExclusion, 'footprintInfo') && ...
            isstruct(headpostExclusion.footprintInfo) && ...
            isfield(headpostExclusion.footprintInfo, 'centerMm')
        center = double(headpostExclusion.footprintInfo.centerMm);
    elseif isfield(headpostExclusion, 'keepoutBoundaryMm') && ...
            ~isempty(headpostExclusion.keepoutBoundaryMm)
        center = mean(double(headpostExclusion.keepoutBoundaryMm), 1);
    end
    if isempty(center)
        return;
    end
    center = center(:)';
    radius = getFieldOrDefault(headpostExclusion, 'keepoutRadiusMm', []);
    if isempty(radius) || ~isscalar(radius) || ~isfinite(radius)
        radius = 16;
    end
    if ~isfield(opts, 'exclusionCenters') || isempty(opts.exclusionCenters)
        opts.exclusionCenters = zeros(0, 3);
        opts.exclusionRadiusMM = zeros(0, 1);
    end
    opts.exclusionCenters = [double(opts.exclusionCenters); center(1:3)];
    opts.exclusionRadiusMM = [double(opts.exclusionRadiusMM(:)); double(radius)];
end

function value = getFieldOrDefault(S, fieldName, defaultValue)
    if isstruct(S) && isfield(S, fieldName) && ~isempty(S.(fieldName))
        value = S.(fieldName);
    else
        value = defaultValue;
    end
end

function out = chooseMode(flag, trueValue, falseValue)
