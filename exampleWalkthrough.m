function txt = safeTagText(value)
    txt = lower(regexprep(char(value), '[^A-Za-z0-9]+', ''));
    maxChars = 24;
    if numel(txt) > maxChars
        txt = txt(1:maxChars);
    end
end

function S = stripGraphicsHandles(S)
    if isstruct(S)
        if isfield(S, 'figure')
            S = rmfield(S, 'figure');
        end
        names = fieldnames(S);
        for i = 1:numel(names)
            value = S.(names{i});
            if isstruct(value)
                S.(names{i}) = stripGraphicsHandles(value);
            end
        end
    end
end

