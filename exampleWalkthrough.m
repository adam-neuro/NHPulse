%% 10 - Optional tES channel-count sweep
% Analysis only: this does not change the manufactured cap recipe. It asks
% whether a larger active-channel budget gives meaningful targeting gains.

tesChannelSweepSparse = {};
tesChannelSweepTable = table();
tesChannelSweepRecommendation = struct();
if cfg.runTesChannelCountSweep
    finalNames = finalCandidateLayout.names(:);
    selectableForSweep = ~ismember(lower(string(finalNames)), ...
        lower(string(finalExcludedTesElectrodeNames)));
    maxSweepCount = nnz(selectableForSweep);
    sweepCounts = unique([cfg.tesChannelSweepCounts(:); cfg.nTes]);
    sweepCounts = sweepCounts(sweepCounts >= 4 & mod(sweepCounts, 2) == 0 & ...
        sweepCounts <= maxSweepCount);

    nSweep = numel(sweepCounts);
    tesChannelSweepSparse = cell(nSweep, 1);
    requestedCount = zeros(nSweep, 1);
    effectiveCount = zeros(nSweep, 1);
    objectiveVm = zeros(nSweep, 1);
    totalAbsCurrentMa = zeros(nSweep, 1);
    selectedNamesByCount = cell(nSweep, 1);

    for kIdx = 1:nSweep
        kTes = sweepCounts(kIdx);
        tesChannelSweepSparse{kIdx} = acsOptimizeSparseRoastLeadField( ...
            finalCandidateLayout.t1File, ...
            finalLeadField.simulationTag, ...
            tesTargetVoxel, ...
            'orientation', tesTargetOrientation, ...
            'targetRadiusMm', 2, ...
            'activeElectrodeCount', kTes, ...
            'totalCurrentMa', cfg.tesTotalCurrentMa, ...
            'maxCurrentPerElectrodeMa', cfg.tesMaxCurrentPerElectrodeMa, ...
            'optType', 'wls-l1per', ...
            'desiredIntensityVm', 0.5, ...
            'focalityK', 0.005, ...
            'searchMode', leadFieldSearchMode, ...
            'excludedElectrodeNames', finalExcludedTesElectrodeNames, ...
            'targetingTag', sprintf('%s_lf%d_tesSweep%02d', ...
            cfg.leadFieldDesignTag, finalCandidateCount, kTes), ...
            'showFigures', false, ...
            'saveFigures', false, ...
            'verbose', true);

        s = tesChannelSweepSparse{kIdx};
        absCurr = abs(s.currentsMa(:));
        thresholdMa = max(cfg.tesChannelSweepEffectiveCurrentThresholdMa, ...
            cfg.tesChannelSweepEffectiveCurrentFraction * max(absCurr));
        requestedCount(kIdx) = kTes;
        effectiveCount(kIdx) = nnz(absCurr >= thresholdMa);
        objectiveVm(kIdx) = s.objectiveVm;
        totalAbsCurrentMa(kIdx) = sum(absCurr);
        selectedNamesByCount{kIdx} = s.selectedNames(:);
    end

    bestSoFarObjectiveVm = cummax(objectiveVm);
    bestObjectiveVm = max(bestSoFarObjectiveVm);
    plateauRows = find(bestSoFarObjectiveVm >= ...
        cfg.tesChannelSweepPlateauFractionOfBest * bestObjectiveVm);
    recommendedTesCount = NaN;
    if ~isempty(plateauRows)
        recommendedTesCount = requestedCount(plateauRows(1));
    end

    tesChannelSweepTable = table(requestedCount, effectiveCount, ...
        objectiveVm, bestSoFarObjectiveVm, totalAbsCurrentMa, ...
        selectedNamesByCount, ...
        'VariableNames', {'requestedTesCount', 'effectiveActiveCount', ...
        'objectiveVm', 'bestSoFarObjectiveVm', 'totalAbsCurrentMa', ...
        'selectedNames'});
    tesChannelSweepRecommendation = struct( ...
        'recommendedTesCount', recommendedTesCount, ...
        'bestObjectiveVm', bestObjectiveVm, ...
        'plateauFractionOfBest', cfg.tesChannelSweepPlateauFractionOfBest);
    disp(tesChannelSweepTable);

    sweepTag = regexprep(sprintf('%s_%s_lf%d', ...
        cfg.subjectId, cfg.leadFieldDesignTag, finalCandidateCount), ...
        '[^\w-]', '_');
    tesChannelSweepReportMat = fullfile(P.capWorkFolder, ...
        [sweepTag '_tesChannelSweep.mat']);
    save(tesChannelSweepReportMat, 'tesChannelSweepSparse', ...
        'tesChannelSweepTable', 'tesChannelSweepRecommendation');
end

