%% NHPulse Synthetic Example Walkthrough
% This public-facing walkthrough creates tiny synthetic, ROAST-ready anatomy
% and exercises the main NHPulse workflow: canonical scalp extraction,
% printer-bed cropping, ear/face exclusions, implant placement, a PLA
% fit-check scaffold, fiducial bookkeeping, target selection, dummy or ROAST
% leadfield-based tES
% layout growth, EEG interleaving, and dual-material cap STL export.
%
% The synthetic head is intentionally cartoon-like. It is useful for checking
% installation, file formats, coordinate plumbing, and cap-layout code paths;
% it is not anatomically realistic and should not be used for scientific
% simulation claims.
%
% ROAST credit: NHPulse builds on ROAST. Please cite ROAST and the relevant
% papers listed in CITATION.md when using this code.
%
% Safety note: this is research software, not a medical device.

%% 00 - Configure MATLAB Path And Demo Settings
% Run this cell from the repository root.

% clear;  % Uncomment when intentionally starting a clean MATLAB session.
% clc;

repoRoot = fileparts(mfilename('fullpath'));
if isempty(repoRoot)
    repoRoot = pwd;
end

setNHPulsePath('repoRoot', repoRoot);
P = acsPaths();
if isempty(P.configFile)
    fprintf(['No local.paths.json found; using default repo-local outputs.\n', ...
        'Run nhpulseConfigureLocalPaths if you want to save machine-specific paths.\n']);
end

cfg = struct();
cfg.subjectId = 'nhpulseSyntheticDemo';
cfg.outputDir = fullfile(P.outputRoot, 'syntheticMwe', cfg.subjectId);
cfg.force = true;
cfg.showFigures = true;
cfg.saveFigures = true;

% Set true to manually exercise the picker/refinement GUIs. This is the
% default for the public walkthrough because it demonstrates the intended
% review/user experience. Set false for a deterministic, mostly non-blocking
% smoke run. After a first successful pass, set cfg.force=false when you want
% saved GUI choices and generated products to be reused.
cfg.interactiveSelections = true;

cfg.fitCheckElectrodes = 6;
cfg.initialTesCandidates = 8;
cfg.nGrowthSteps = 2;
cfg.nNewCandidatesPerStep = 2;
cfg.activeTesChannels = 4;
cfg.nEegChannels = 4;
% Use 'dummy' for a fast software walkthrough. Use 'roast' to run actual
% ROAST/GetDP leadfield solves on the tiny synthetic model and time them.
cfg.leadFieldMode = 'dummy';
cfg.dummyLeadFieldMeshSpacingMm = 3;
cfg.realLeadFieldResampling = 'off';
% Use an enlarged demo disc for the optional real-ROAST path. The production
% BioSemi-pin model is intentionally tiny and can be lost by the coarse toy
% tetrahedral mesh, which makes for a brittle reviewer smoke test.
cfg.realLeadFieldElectrodeModel = 'syntheticDemo';
cfg.realLeadFieldMeshOptions = struct('radbound', 2, ...
    'angbound', 30, 'distbound', 0.2, 'reratio', 3, 'maxvol', 2);
cfg.realLeadFieldTagSuffix = 'airgel01';
cfg.realLeadFieldShowFigures = false;
cfg.targetRadiusMm = 4;
cfg.targetOrientation = [0 0 1];
cfg.sparseSearchMode = 'developmentHeuristic';
cfg.headpostMarginMm = 4;
cfg.syntheticCropAxis = [-0.112 -0.112 0.987];
cfg.syntheticCropDistanceMm = 32.60;
cfg.demoHeadpostScale = 0.60;
cfg.demoHeadpostRadiusMm = 12.625 * cfg.demoHeadpostScale;
cfg.layoutEdgeMarginMm = 3;
cfg.layoutBedMarginMm = 1;
cfg.layoutNormalUpDotMin = 0;
cfg.demoElectrodeFootprintDiameterMm = 9;
cfg.demoElectrodeClearanceMm = 0.5;
cfg.demoMinDistanceMm = 10;
cfg.demoEegTesClearanceMm = 10;
cfg.fitCheckGridSurfaceMaxFaces = 220;
cfg.finalManufacturingSurfaceMaxFaces = 350;
cfg.finalRailSurfaceMaxFaces = 350;
cfg.finalRailEdgeMarginMm = 2;

fprintf('NHPulse synthetic walkthrough output:\n  %s\n', cfg.outputDir);
nhpulseEnsureWritableDir(cfg.outputDir, 'synthetic walkthrough output');
restoreFigureWindowStyle = setTemporaryFigureWindowStyle('normal');

%% 01 - Create Synthetic ROAST-Ready Anatomy
% This creates:
%   *_T1.nii
%   *_T1_T1orT2_SPM_masks.nii
%   synthetic model/phone fiducials
%   a synthetic phone-scan-like PLY/MAT surface
%
% The returned struct has syntheticOut.roastReady, which is the smallest
% useful public entry point into the NHPulse pipeline.

syntheticOut = nhpulseCreateSyntheticRoastReadyData(cfg.outputDir, ...
    'subjectId', cfg.subjectId, ...
    'force', cfg.force, ...
    'showFigure', cfg.showFigures, ...
    'saveFigure', cfg.saveFigures);

disp(syntheticOut.roastReady)
[roastFolder, t1Stem] = fileparts(syntheticOut.t1File);

%% 02 - Build A ROAST-Derived Full-Head Scalp Mesh Cache
% NHPulse uses a single canonical scalp surface for the capMaker side of the
% pipeline. For real data this can later be warped to phone/LiDAR or digitizer
% traces; this synthetic example keeps the ROAST-derived mesh unchanged.

fullHeadScalpCacheFile = fullfile(cfg.outputDir, ...
    sprintf('%s_roastScalpSkinMesh.mat', cfg.subjectId));

fullHeadScalp = acsBuildRoastScalpSkinCache(syntheticOut, ...
    'outputFile', fullHeadScalpCacheFile, ...
    'force', cfg.force, ...
    'maxFaces', 8000, ...
    'showFigures', cfg.showFigures, ...
    'saveFigures', cfg.saveFigures, ...
    'verbose', true);

fprintf('Full-head scalp cache mesh: %d vertices, %d faces\n', ...
    fullHeadScalp.meshStats.nVertices, fullHeadScalp.meshStats.nFaces);

%% 03 - Crop The Scalp To The Printable Cap Footprint
% The capMaker manufacturing frame has Z=0 at the printer-bed/crop plane. The
% GUI is seeded with a deterministic synthetic crop plane. Use it as-is or
% adjust it to practice the manual crop workflow.

capSkinCacheFile = fullfile(cfg.outputDir, ...
    sprintf('%s_printerBedSkinMesh.mat', cfg.subjectId));
cropPlaneFile = fullfile(cfg.outputDir, ...
    sprintf('%s_printerBedCropPlane.mat', cfg.subjectId));

cropMode = chooseMode(cfg.interactiveSelections, 'select', 'auto');
capSkin = acsCropWarpedSkinCacheToPrinterBed(fullHeadScalp.cacheFile, ...
    'outputFile', capSkinCacheFile, ...
    'cropPlaneFile', cropPlaneFile, ...
    'cropPlaneMode', cropMode, ...
    'cropSide', 'top', ...
    'initialCropAxis', cfg.syntheticCropAxis, ...
    'initialCropDistance', cfg.syntheticCropDistanceMm, ...
    'skinMaxFaces', 1200, ...
    'keepLargestSkinComponent', true, ...
    'force', cfg.force, ...
    'showFigures', cfg.showFigures, ...
    'saveFigures', cfg.saveFigures, ...
    'verbose', true);

fprintf('Printable scalp cache mesh: %d vertices, %d faces\n', ...
    capSkin.meshStats.skin.nVertices, capSkin.meshStats.skin.nFaces);

%% 04 - Define Ear And Painted Manufacturing Exclusions
% Ear exclusions keep electrodes and cap rails away from sensitive/highly
% curved regions. With cfg.interactiveSelections=true, the GUI opens so the
% user can practice moving the ear spheres and painting additional face/skin
% vertices. Set the flag false for deterministic auto proposals.

earExclusionFile = fullfile(cfg.outputDir, ...
    sprintf('%s_printerBedEarExclusions.mat', cfg.subjectId));
earEditMode = chooseMode(cfg.interactiveSelections, 'always', 'auto');

earExclusions = acsSelectEarExclusionSpheres(capSkin.cacheFile, ...
    'outputFile', earExclusionFile, ...
    'force', cfg.force, ...
    'editMode', earEditMode, ...
    'showFigures', cfg.interactiveSelections, ...
    'saveFigures', cfg.saveFigures, ...
    'showVertexOverlay', true, ...
    'showStrapPreview', true, ...
    'verbose', true);

%% 05 - Place A Synthetic Headpost And Build Its Cap Keepout
% Real workflows can pass a Polhemus/phone-scan-derived implant trace here.
% The synthetic walkthrough creates a circular trace, places the simplified
% headpost STL, and then derives the tight cylindrical keepout used by cap
% layout/manufacturing.

headpostTraceFile = fullfile(cfg.outputDir, ...
    sprintf('%s_syntheticHeadpostTrace.mat', cfg.subjectId));
headpostTrace = nhpulseCreateSyntheticHeadpostTrace(capSkin.cacheFile, ...
    'outputFile', headpostTraceFile, ...
    'radiusMm', cfg.demoHeadpostRadiusMm, ...
    'nPoints', 72, ...
    'showFigure', cfg.showFigures, ...
    'saveFigure', cfg.saveFigures, ...
    'verbose', true);

headpostPlacementFile = fullfile(cfg.outputDir, ...
    sprintf('%s_headpostPlacement.mat', cfg.subjectId));
headpostPlacement = acsPlanHeadpostPlacement(headpostTrace, capSkin.cacheFile, ...
    'maskFile', syntheticOut.maskFile, ...
    'meshScale', cfg.demoHeadpostScale, ...
    'interactive', cfg.interactiveSelections, ...
    'outputFile', headpostPlacementFile, ...
    'force', cfg.force, ...
    'reuseExistingPose', true, ...
    'bendStraps', true, ...
    'bendThicknessMode', 'skullNormal', ...
    'headpostRefineMaxEdgeMm', 4, ...
    'headpostRefineMaxIterations', 2, ...
    'showFigures', cfg.showFigures, ...
    'saveFigures', cfg.saveFigures, ...
    'verbose', true);

headpostExclusionFile = fullfile(cfg.outputDir, ...
    sprintf('%s_headpostKeepout.mat', cfg.subjectId));
headpostExclusion = acsMakeHeadpostExclusionFromPlacement( ...
    headpostPlacement, capSkin.cacheFile, ...
    'outputFile', headpostExclusionFile, ...
    'marginMm', cfg.headpostMarginMm, ...
    'footprintMode', 'postCylinder', ...
    'force', cfg.force, ...
    'showFigures', cfg.showFigures, ...
    'saveFigures', cfg.saveFigures, ...
    'verbose', true);

%% 06 - Export A Fast PLA Fit-Check STL
% A sparse PLA scaffold is useful for gross fit checks before committing to a
% full TPE-on-PLA print. This scaffold uses a toy marker layout and the same
% ear/painted/headpost manufacturing keepouts used by the final cap.

fitCheckCustomLocationsFile = fullfile(roastFolder, ...
    [t1Stem '_fitCheckCustomLocations']);

fitCheckTargetOptions = baseCapTargetOptions(cfg);
fitCheckTargetOptions = addHeadpostKeepout( ...
    fitCheckTargetOptions, headpostExclusion);

fitCheckLayout = acsMakeRoastCapMakerLayout(syntheticOut, ...
    'surfaceSource', 'capMaker', ...
    'subjectId', cfg.subjectId, ...
    'skinCacheFile', capSkin.cacheFile, ...
    'nElectrodes', cfg.fitCheckElectrodes, ...
    'outputFile', fitCheckCustomLocationsFile, ...
    'targetOptions', fitCheckTargetOptions, ...
    'earExclusionMode', 'never', ...
    'earExclusionFile', earExclusionFile, ...
    'strapExclusionMode', 'auto', ...
    'forceLayout', cfg.force, ...
    'showFigures', cfg.showFigures, ...
    'saveFigures', cfg.saveFigures, ...
    'verbose', true);

fitCheckDir = fullfile(cfg.outputDir, 'fitChecks', ...
    sprintf('%s_sparsePlaFitCheck', cfg.subjectId));

fitCheck = acsBuildCapMakerFitCheckStl(fitCheckLayout, ...
    'skinCacheFile', capSkin.cacheFile, ...
    'outputDir', fitCheckDir, ...
    'fitCheckTag', sprintf('%s_sparsePlaFitCheck', cfg.subjectId), ...
    'force', cfg.force, ...
    'includeElectrodeMarkers', true, ...
    'gridSurfaceMaxFaces', cfg.fitCheckGridSurfaceMaxFaces, ...
    'railEdgeMarginMm', 2, ...
    'earExclusionMode', 'never', ...
    'earExclusionFile', earExclusionFile, ...
    'earRailExclusionGeometry', 'sphere3d', ...
    'implantExclusionFile', {headpostExclusionFile}, ...
    'componentCleanupMode', 'largest', ...
    'showFigures', cfg.showFigures, ...
    'saveFigures', cfg.saveFigures, ...
    'verbose', true);

fprintf('Synthetic fit-check STL:\n  %s\n', fitCheck.stlFile);

%% 07 - Mark Or Reuse Model Fiducials
% Fiducials are used for registering digitizer/scan data to MRI/capMaker
% space. The synthetic generator already knows the matching locations. Set
% cfg.interactiveSelections=true to practice selecting them on the mesh.

fiducialLabels = {'Nas', 'Lpa', 'Rpa', 'Ini'};
modelFiducialsFile = fullfile(cfg.outputDir, ...
    sprintf('%s_modelFiducialsOnScalp.mat', cfg.subjectId));

if cfg.interactiveSelections
    modelFiducials = acsSelectModelFiducials(fullHeadScalp.cacheFile, ...
        'fiducialLabels', fiducialLabels, ...
        'meshStage', 'fullHead', ...
        'outputFile', modelFiducialsFile, ...
        'force', cfg.force, ...
        'editMode', 'always', ...
        'showFigures', true, ...
        'saveFigures', cfg.saveFigures, ...
        'verbose', true);
else
    modelFiducials = syntheticOut.modelFiducials;
    out = modelFiducials; %#ok<NASGU>
    outForSave = modelFiducials; %#ok<NASGU>
    save(modelFiducialsFile, 'out', 'outForSave', '-v7.3');
    fprintf('Reused generated synthetic model fiducials:\n  %s\n', ...
        modelFiducialsFile);
end

disp(table(modelFiducials.labels(:), modelFiducials.coordinatesMm(:, 1), ...
    modelFiducials.coordinatesMm(:, 2), modelFiducials.coordinatesMm(:, 3), ...
    'VariableNames', {'Label', 'Xmm', 'Ymm', 'Zmm'}));

%% 08 - Select A Brain Target Voxel
% For a real experiment this is where the user chooses the target brain voxel.
% The synthetic run uses a stored toy target unless interactive selections are
% enabled.

targetVoxelFile = fullfile(cfg.outputDir, ...
    sprintf('%s_demoTargetVoxel.mat', cfg.subjectId));

if cfg.interactiveSelections
    targetPick = acsLabelVolumeOrientation(syntheticOut.t1File, ...
        'orientationCode', 'ras', ...
        'volumeLabel', 'Synthetic demo T1', ...
        'initialVoxel', syntheticOut.demoTargets.targetVoxel, ...
        'voxelSelectionMode', 'single', ...
        'waitForDone', true, ...
        'doneButtonLabel', 'Accept target', ...
        'showFigures', true, ...
        'saveFigures', cfg.saveFigures, ...
        'outputDir', fullfile(cfg.outputDir, 'qc'), ...
        'outputName', sprintf('%s_targetVoxelPicker', cfg.subjectId), ...
        'closeFigure', false, ...
        'verbose', true);
    targetVoxel = double(targetPick.selectedVoxels(1, :));
else
    targetVoxel = double(syntheticOut.demoTargets.targetVoxel);
    targetPick = struct('selectedVoxels', targetVoxel, ...
        'source', struct('file', syntheticOut.t1File), ...
        'note', 'Generated synthetic target reused without opening picker.');
end

targetSelection = struct();
targetSelection.createdOn = char(datetime('now'));
targetSelection.type = 'syntheticTargetSelection';
targetSelection.targetVoxel = targetVoxel;
targetSelection.targetWorldMm = targetVoxel .* syntheticOut.geometry.voxelSizeMm;
targetSelection.source = stripGraphicsHandles(targetPick);
save(targetVoxelFile, 'targetSelection', '-v7.3');

fprintf('Demo target voxel: [%g %g %g]\n', targetVoxel);

%% 09 - Build The Initial tES Candidate Layout
% These are candidate tES contacts, not the final active montage. The layout
% uses the ear, strap, and headpost keepouts defined above.

customLocationsFile = fullfile(roastFolder, [t1Stem '_customLocations']);
targetOptions = baseCapTargetOptions(cfg);
targetOptions = addHeadpostKeepout(targetOptions, headpostExclusion);

candidateLayout = acsMakeRoastCapMakerLayout(syntheticOut, ...
    'surfaceSource', 'capMaker', ...
    'subjectId', cfg.subjectId, ...
    'skinCacheFile', capSkin.cacheFile, ...
    'nElectrodes', cfg.initialTesCandidates, ...
    'outputFile', customLocationsFile, ...
    'targetOptions', targetOptions, ...
    'earExclusionMode', 'never', ...
    'earExclusionFile', earExclusionFile, ...
    'strapExclusionMode', 'auto', ...
    'forceLayout', true, ...
    'showFigures', cfg.showFigures, ...
    'saveFigures', cfg.saveFigures, ...
    'verbose', true);

%% 10 - Grow tES Candidates With Dummy Or ROAST Leadfields
% The default dummy mode lets reviewers exercise sparse optimization and UCB
% candidate growth quickly. Set cfg.leadFieldMode='roast' to run real
% ROAST/GetDP leadfield solves on the tiny synthetic model and time the path.

growthHistory = repmat(struct('layout', [], 'leadField', [], ...
    'sparse', [], 'proposal', []), cfg.nGrowthSteps + 1, 1);
currentLayout = candidateLayout;
currentLeadField = [];
currentSparse = [];

fprintf('\nSynthetic tES growth walkthrough\n');
fprintf('  iterations: %d growth step(s) plus one final sparse solve\n', ...
    cfg.nGrowthSteps);
fprintf('  lead-field mode: %s\n', cfg.leadFieldMode);
if useRealLeadFields(cfg)
    fprintf('  ROAST/GetDP solves can still take minutes, even for this toy head.\n');
else
    fprintf('  lead fields: dummy/synthetic, not a physical ROAST solve\n');
end
fprintf('  sparse search mode: %s\n', cfg.sparseSearchMode);

for g = 1:(cfg.nGrowthSteps + 1)
    currentCount = numel(currentLayout.names);
    leadFieldTag = leadFieldTagForMode(cfg, currentCount);
    if g <= cfg.nGrowthSteps
        fprintf('\nGrowth iteration %d/%d: %d candidate contacts\n', ...
            g, cfg.nGrowthSteps, currentCount);
    else
        fprintf('\nFinal sparse solve on %d candidate contacts\n', currentCount);
    end
    leadTimer = tic;
    if useRealLeadFields(cfg)
        fprintf('  Step 1: running ROAST leadfield solve (%s)...\n', leadFieldTag);
        currentLeadField = acsGenerateRoastLeadField(currentLayout, ...
            'simulationTag', leadFieldTag, ...
            'resampling', cfg.realLeadFieldResampling, ...
            'segMaskFile', syntheticOut.maskFile, ...
            'electrodeModel', cfg.realLeadFieldElectrodeModel, ...
            'roastOptions', realLeadFieldRoastOptions(cfg), ...
            'showFigures', cfg.realLeadFieldShowFigures, ...
            'execute', true, ...
            'saveReport', true);
    else
        fprintf('  Step 1: writing dummy lead field (%s)...\n', leadFieldTag);
        currentLeadField = acsGenerateDummyRoastLeadField(currentLayout, ...
            'simulationTag', leadFieldTag, ...
            'meshSpacingMm', cfg.dummyLeadFieldMeshSpacingMm, ...
            'force', cfg.force, ...
            'saveReport', true, ...
            'verbose', true);
    end
    fprintf('  Step 1 complete in %.1f s.\n', toc(leadTimer));

    fprintf('  Step 2: optimizing sparse %d-contact montage...\n', ...
        cfg.activeTesChannels);
    currentSparse = acsOptimizeSparseRoastLeadField( ...
        currentLayout.t1File, currentLeadField.simulationTag, targetVoxel, ...
        'orientation', cfg.targetOrientation, ...
        'targetRadiusMm', cfg.targetRadiusMm, ...
        'activeElectrodeCount', cfg.activeTesChannels, ...
        'searchMode', cfg.sparseSearchMode, ...
        'targetingTag', sprintf('%s_demoTes%d', ...
            cfg.subjectId, cfg.activeTesChannels), ...
        'maxFilenameBaseChars', 72, ...
        'returnMeshField', false, ...
        'showFigures', cfg.showFigures, ...
        'saveFigures', cfg.saveFigures, ...
        'saveReport', true, ...
        'verbose', true);

    growthHistory(g).layout = currentLayout;
    growthHistory(g).leadField = currentLeadField;
    growthHistory(g).sparse = currentSparse;

    if g > cfg.nGrowthSteps
        break;
    end

    fprintf('  Step 3: proposing %d new candidate contact(s) with UCB...\n', ...
        cfg.nNewCandidatesPerStep);
    proposal = acsProposeRoastCandidateGrowth(currentLayout, currentSparse, ...
        'nNew', cfg.nNewCandidatesPerStep, ...
        'poolSize', 48, ...
        'kernelSigmaMm', 'auto', ...
        'acquisitionMode', 'ucb', ...
        'ucbBeta', 1, ...
        'electrodeFootprintDiameterMm', cfg.demoElectrodeFootprintDiameterMm, ...
        'electrodeClearanceMm', cfg.demoElectrodeClearanceMm, ...
        'minDistanceFromExistingMm', cfg.demoMinDistanceMm, ...
        'minDistanceAmongNewMm', cfg.demoMinDistanceMm, ...
        'targetOptions', targetOptions, ...
        'earExclusionMode', 'never', ...
        'earExclusionFile', earExclusionFile, ...
        'strapExclusionMode', 'auto', ...
        'makeLayout', true, ...
        'outputFile', customLocationsFile, ...
        'forceLayout', true, ...
        'proposalTag', sprintf('%s_demoGrow%02d', cfg.subjectId, g), ...
        'maxFilenameBaseChars', 72, ...
        'showFigures', cfg.showFigures, ...
        'saveFigures', cfg.saveFigures, ...
        'saveReport', true, ...
        'verbose', true);

    growthHistory(g).proposal = proposal;
    currentLayout = proposal.expandedLayout;
    fprintf('  Iteration %d complete: %d -> %d candidates.\n', ...
        g, currentCount, numel(currentLayout.names));
end

finalCandidateLayout = currentLayout;
finalLeadField = currentLeadField;
finalSparse = currentSparse;

fprintf('Final synthetic candidate layout: %d contacts\n', ...
    numel(finalCandidateLayout.names));
fprintf('Selected tES contacts: %s\n', ...
    strjoin(cellstr(finalSparse.selectedNames(:))', ', '));

