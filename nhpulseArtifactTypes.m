function registry = nhpulseArtifactTypes(varargin)
% NHPULSEARTIFACTTYPES Return the extensible NHPulse artifact hierarchy.
%
% registry = nhpulseArtifactTypes() returns built-in artifact definitions.
% The hierarchy describes stages and valid parent relationships without
% changing where pipeline files are written.
%
% registry = nhpulseArtifactTypes('additionalTypes', definitions) appends or
% replaces definitions by type name. Custom definitions may omit fields; the
% defaults documented by an entry in the returned registry are supplied.

    p = inputParser;
    addParameter(p, 'additionalTypes', struct([]), @isstruct);
    parse(p, varargin{:});

    registry = builtInTypes();
    additional = p.Results.additionalTypes;
    for i = 1:numel(additional)
        definition = normalizeDefinition(additional(i));
        idx = find(strcmp({registry.type}, definition.type), 1);
        if isempty(idx)
            registry(end + 1, 1) = definition; %#ok<AGROW>
        else
            registry(idx) = definition;
        end
    end
end

