function value = define(type, label, stage, order, policy, parents, ...
        extensions, priority, patterns)
    value = emptyDefinition();
    value.type = type;
    value.label = label;
    value.stage = stage;
    value.stageOrder = order;
    value.parentPolicy = policy;
    value.allowedParentTypes = parents(:).';
    value.extensions = extensions(:).';
    value.legacyPriority = priority;
    value.legacyPatterns = patterns(:).';
    value.description = label;
end

function value = normalizeDefinition(input)
    value = emptyDefinition();
    names = fieldnames(input);
    for i = 1:numel(names)
        if ~isfield(value, names{i})
            error('nhpulseArtifactTypes:UnknownField', ...
                'Unknown artifact definition field "%s".', names{i});
        end
        value.(names{i}) = input.(names{i});
    end
    if isempty(value.type)
        error('nhpulseArtifactTypes:MissingType', ...
            'Each artifact definition requires a nonempty type.');
    end
    value.type = char(value.type);
    value.label = char(value.label);
    value.stage = char(value.stage);
    value.parentPolicy = lower(char(value.parentPolicy));
    if ~any(strcmp(value.parentPolicy, {'root', 'listed', 'any'}))
        error('nhpulseArtifactTypes:BadParentPolicy', ...
            'parentPolicy must be root, listed, or any.');
    end
    value.allowedParentTypes = cellstr(value.allowedParentTypes);
    value.extensions = cellfun(@lower, cellstr(value.extensions), ...
        'UniformOutput', false);
    value.legacyPatterns = cellstr(value.legacyPatterns);
end

function value = emptyDefinition()
    value = struct('type', '', 'label', '', 'stage', 'extension', ...
        'stageOrder', 999, 'description', '', 'parentPolicy', 'any', ...
        'allowedParentTypes', {{}}, 'extensions', {{}}, ...
        'legacyPriority', 0, 'legacyPatterns', {{}});
end
